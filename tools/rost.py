#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
rost.py — ГЕЙТ РОСТА: следующий ролик богаче предыдущего, а не тот же самый.

ЗАЧЕМ. Требование студии: «каждый последующий ролик должен быть сложнее,
интереснее, красивее предыдущего; персонаж должен двигаться естественно и
аутентично». Замер показал обратное движение — каталог БЕДНЕЛ.

  · СЛОВАРЬ КАМЕРЫ. Движок знает десять приёмов и все десять уже стояли в
    роликах: `close-up`, `extreme-close-up`, `angle`, `dutch`, `shake`,
    `zoom-to`, `pan-to`, `reset` сверх `wide` и `medium`. Ранние ролики брали
    по четыре-восемь приёмов на штуку. Последние ДВАДЦАТЬ роликов — ровно два:
    общий и средний. Ни одного крупного плана, ни наезда, ни наклона.
  · ПЕРЕМЕЩЕНИЕ. `moves-to` по каталогу встречается сто сорок девять раз.
    В одиннадцати последних роликах — НОЛЬ. Персонаж не ходит по кадру совсем:
    он стоит на месте и меняет накладки.
  · БИБЛИОТЕКА ПОЗ. В риге двести три позы, шестьдесят семь не использованы ни
    разу — вся семья сидя (`sit`, `na_stule`, `lotos`), лёжа, бег, прыжок,
    шесть танцевальных, три с сигаретой, ракурсы `high_angle`/`low_angle`.
    При этом «Ложь» и «Стоицизм» не ввели НИ ОДНОЙ новой позы.

Однообразие, на которое смотрит `emocii`, — это одинаковый ЗАРЯД. Здесь мерка
другая и независимая: ролик может быть эмоционально новым и при этом снят тем
же одним планом с неподвижной фигурой. Зритель это видит раньше, чем слышит.

ЧТО ПРОВЕРЯЕТСЯ (ролик сверяется с ПРЕДЫДУЩИМ по порядку сдачи,
`tools/productions.json`):

  1. приёмов камеры не меньше трёх — сверх пары «общий плюс средний» есть хотя
     бы один третий: крупный, наезд, тряска, наклон;
  2. персонаж хотя бы раз перемещается по кадру (`moves-to`);
  3. ролик вводит не меньше двух поз, ни разу не встречавшихся в ряду до него;
  4. словарь поз не беднее предыдущего больше чем на десятую часть.

ПОРОГИ СНЯТЫ С КАТАЛОГА. Три приёма камеры держали одиннадцать роликов из
тридцати шести (до восьми у `prison-intro`), перемещение — двадцать, две новые
позы — четырнадцать. Это не планка «выше, чем было когда-либо»: это планка
«не ниже того, что завод уже умел». Ресурс под требование есть: шестьдесят
семь неиспользованных поз и восемь неиспользованных приёмов камеры.

ПОЧЕМУ «НЕ БЕДНЕЕ», А НЕ «БОГАЧЕ КАЖДЫЙ РАЗ». Монотонный рост числа поз
упирается в потолок за десяток роликов и дальше начинает вредить: ролик
набивается жестами ради счётчика. Требование роста здесь несёт пункт 3 —
каждый раз в кадре есть то, чего в этом ряду ещё не было.

Использование:
    python3 tools/rost.py examples/lektorij/lozh.anim
    python3 tools/rost.py --all
"""

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

CAM = re.compile(r"^\s*camera\s+([a-z-]+)", re.M)
MOV = re.compile(r"^\s*\w+\s+moves-to\b", re.M)
POZA = re.compile(r'^\s*\w+\s+(?:pose|overlays)\s+"([^"]+)"', re.M)
SET = re.compile(r'^\s*scene\s+"[^"]+"\s*\([^)]*set:\s*(\w+)', re.M)
HIDES = re.compile(r'^\s*(\w+)\s+hides\b', re.M)
SHOWS = re.compile(r'^\s*(\w+)\s+shows\b', re.M)

KAMERA = 3            # приёмов камеры на ролик
NOVYH = 2             # поз, которых в ряду ещё не было
OBEDNENIE = 0.90      # доля словаря поз от предыдущего ролика

#  ЗАКАДРОВЫЙ РОЛИК МЕРЯЕТСЯ НЕ ПОЗАМИ, А ЛОКАЦИЯМИ.
#
#  Гейт вырос из замечания «каждый следующий ролик сложнее предыдущего» и
#  считает богатство по фигуре: сколько поз, сколько перемещений. Это верно,
#  пока фигура в кадре. Ролик 27 «Парус» — притча, рассказанная поверх
#  рисунков: раскадровка студии не содержит ни одного плана с персонажем, а
#  гребца рисовать ригом нельзя, потому что он СИДИТ. Фримен там объявлен и
#  скрыт: голос ведёт, в кадре его нет.
#
#  Мерить такой ролик позами — всё равно что мерить радиоспектакль мимикой.
#  Богатство картинки в нём живёт в другом месте: в числе РАЗНЫХ ЛОКАЦИЙ и в
#  приёмах камеры. Планка ставится по ряду: одиннадцать локаций против пяти-
#  шести у говорящих роликов — это не поблажка, а более высокий барьер.
#
#  Признак строгий и структурный: рассказчик скрыт (`hides`) и НИ РАЗУ не
#  показан (`shows`). Ролик, где персонаж просто забыт, под него не подпадёт —
#  там `hides` нет вовсе, и гейт сработает по-старому.
LOKACIJ = 8           # разных локаций в закадровом ролике


def razbor(path):
    t = Path(path).read_text(encoding="utf-8")
    return {
        "kamery": set(CAM.findall(t)),
        "hodit": len(MOV.findall(t)),
        "pozy": set(POZA.findall(t)),
        "sety": set(SET.findall(t)),
        "zakadrom": bool(HIDES.findall(t)) and not SHOWS.findall(t),
    }


def ryad():
    """(id, путь к .anim) в порядке сдачи — только существующие файлы."""
    prods = json.loads((ROOT / "tools/productions.json").read_text(encoding="utf-8"))
    out = []
    for p in prods["productions"]:
        f = ROOT / p["anim"]
        if f.exists():
            out.append((p["id"], f))
    return out


def proverit(target):
    r = ryad()
    ids = [i for i, _ in r]
    tid = Path(target).stem
    if tid not in ids:
        return [("ролик в реестре продакшена", False,
                 f"«{tid}» нет в tools/productions.json — порядок сдачи "
                 f"неизвестен, сравнивать не с чем")]
    k = ids.index(tid)
    ja = razbor(target)
    #  «Новая поза» — новая ДЛЯ РЯДА, а не для истории вообще: ролик, который
    #  идёт первым, ничего не обязан вводить, а двадцатый обязан.
    bylo = set()
    for _, f in r[:k]:
        bylo |= razbor(f)["pozy"]
    pred = razbor(r[k - 1][1]) if k else None

    out = []
    out.append((f"приёмов камеры {len(ja['kamery'])} из десяти, что умеет движок",
                len(ja["kamery"]) >= KAMERA,
                f"снято на {', '.join(sorted(ja['kamery'])) or 'ничём'} — "
                f"{len(ja['kamery'])} приём(а) при норме {KAMERA}. Крупный план, "
                f"наезд, тряска и наклон движком поддержаны и в роликах уже "
                f"стояли; ролик на двух планах смотрится как запись, а не съёмка"))

    if ja["zakadrom"]:
        #  Рассказчик за кадром — считаем локации вместо поз (см. шапку).
        out.append((f"локаций в закадровом ролике: {len(ja['sety'])}",
                    len(ja["sety"]) >= LOKACIJ,
                    f"{len(ja['sety'])} локаций при норме {LOKACIJ}. Персонажа "
                    f"в кадре нет, держать картинку нечем, кроме смены места: "
                    f"закадровый ролик на пяти локациях — это радио с заставкой"))
        return out

    out.append(("персонаж перемещается по кадру", ja["hodit"] > 0,
                "ни одного `moves-to`: фигура весь ролик стоит в одной точке и "
                "меняет только накладки. Так снят каждый из одиннадцати "
                "последних роликов, и это читается как неподвижность"))

    novye = ja["pozy"] - bylo
    if k:
        out.append((f"новых поз в ряду: {len(novye)}", len(novye) >= NOVYH,
                    f"ролик собран целиком из того, что зритель уже видел "
                    f"({len(novye)} новых при норме {NOVYH}). В риге "
                    f"шестьдесят семь поз, не использованных ни разу"))

    if pred:
        d = len(ja["pozy"]) / max(1, len(pred["pozy"]))
        out.append((f"словарь поз не беднее предыдущего ({d:.2f})",
                    d >= OBEDNENIE,
                    f"{len(ja['pozy'])} поз против {len(pred['pozy'])} у "
                    f"«{r[k - 1][0]}» — ролик проще предыдущего"))
    return out


def main(argv):
    ap = argparse.ArgumentParser(description="Гейт роста ролика")
    ap.add_argument("files", nargs="*")
    ap.add_argument("--all", action="store_true",
                    help="карта богатства по всему ряду")
    a = ap.parse_args(argv)

    if a.all:
        print("\n  КАРТА БОГАТСТВА ПО ПОРЯДКУ СДАЧИ\n")
        bylo = set()
        for i, f in ryad():
            r = razbor(f)
            novye = r["pozy"] - bylo
            bylo |= r["pozy"]
            print(f"    {i:24} камера {len(r['kamery'])}  "
                  f"перемещений {r['hodit']:3}  поз {len(r['pozy']):3}  "
                  f"новых {len(novye):3}")
        print()
        return 0

    if not a.files:
        raise SystemExit("укажи .anim или --all")
    bad = 0
    for f in a.files:
        print(f"\n  РОСТ: {Path(f).name}\n")
        for name, ok, why in proverit(f):
            print(f"    [{'OK  ' if ok else 'ПРОВАЛ'}] {name}")
            if not ok:
                bad += 1
                print(f"             → {why}")
    if bad:
        print(f"\n  Ролик не богаче предыдущего по {bad} признак(ам).\n")
        return 1
    print("\n  Ролик богаче предыдущего.\n")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
