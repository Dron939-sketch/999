#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
cvet.py — ГЕЙТ ЦВЕТНОГО ПЯТНА: ровно одна цветная деталь на ролик.

ПРИЁМ СТУДИИ. Ролик чёрно-белый, и ровно в одной локации живёт ОДНА цветная
деталь. Она не украшение: в ч/б кадре единственное цветное пятно тянет глаз
сильнее любой композиции, и потому оно обязано стоять на теме ролика — как
красная черта на пороге в «Этике», буквально предмет разговора.

Движок этот приём уже держит: насыщенный пиксель ПЕРЕЖИВАЕТ монохромный проход
(`apply_monochrome` в `src/main.rs`: `mx − mn > 55` при `mx > 90`), и остаётся
единственным цветом в кадре. Здесь та же мерка, чтобы гейт и движок считали
цветом одно и то же.

ЧТО ПРОВЕРЯЕТСЯ

  · цветная локация в ролике РОВНО ОДНА. Две — глаз мечется, приём умирает;
    ноль — ролик теряет единственную точку, которую зритель запомнит глазами;
  · пятно маленькое: не больше 3% кадра. Больше — это уже не деталь, а
    цветной кусок декорации, и он спорит с тушью.

Замер по каталогу на день заведения гейта: цвет есть у шести сетов из
шестидесяти с лишним, и самое большое пятно — красная черта «Этики», 2.6%.
Порог 3% поставлен по ней с небольшим запасом.

Использование:
    python3 tools/cvet.py examples/lektorij/lozh.anim
"""

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

IMPORT_SET = re.compile(r'import\s+set\s+\w+\s+from\s+"([^"]+)"')
POROG_DOLI = 0.03          # больше — уже не деталь, а декорация
#  НИЖНИЙ ПОРОГ. Отдельные насыщенные пиксели есть почти в любом растре —
#  следы сжатия, синеватый блик, тёплый край штриха. По каталогу такой шум
#  даёт до 0.1% кадра, а НАМЕРЕННОЕ пятно начинается с половины процента
#  (чайник 0.52%, метки на дверях 0.80%, черта на пороге 2.62%). Порог 0.2%
#  разводит шум и приём: без него гейт объявлял «цветной локацией» кухню со
#  счетами, где цвета шесть сотых процента.
POROG_SHUMA = 0.002


def dolya_cveta(png):
    import numpy as np
    from PIL import Image
    a = np.asarray(Image.open(png).convert("RGB").resize((640, 360)), dtype=int)
    mx, mn = a.max(2), a.min(2)
    return float(((mx - mn > 55) & (mx > 90)).mean())


def main(argv):
    ap = argparse.ArgumentParser(description="Гейт цветного пятна")
    ap.add_argument("anim")
    a = ap.parse_args(argv)

    src = Path(a.anim)
    text = src.read_text(encoding="utf-8")
    cvetnye, bez_rastr = [], []
    for rel in IMPORT_SET.findall(text):
        svg = (src.parent / rel).resolve()
        png = svg.with_suffix(".png")
        if not png.exists():
            #  У части локаций растра рядом нет — они нарисованы вектором.
            #  Тогда цвет считать нечем, и это НЕ провал: гейт честно говорит,
            #  каких файлов не хватает, вместо того чтобы молча их пропустить.
            bez_rastr.append(svg.stem)
            continue
        d = dolya_cveta(png)
        if d > POROG_SHUMA:
            cvetnye.append((svg.stem, d))

    if bez_rastr:
        print(f"  цвет: без растра рядом (считать нечем): {', '.join(bez_rastr)}")

    if len(cvetnye) == 1:
        name, d = cvetnye[0]
        if d > POROG_DOLI:
            print(f"  ЦВЕТНОЕ ПЯТНО СЛИШКОМ БОЛЬШОЕ: {name} — {d * 100:.1f}% "
                  f"кадра при потолке {POROG_DOLI * 100:.0f}%. Это уже "
                  f"декорация, а не деталь: она спорит с тушью")
            return 1
        print(f"  цвет: одно пятно — {name}, {d * 100:.2f}% кадра")
        return 0

    if not cvetnye:
        print("  ЦВЕТНОГО ПЯТНА НЕТ НИ В ОДНОЙ ЛОКАЦИИ. В ч/б ролике "
              "единственное цветное пятно — самая сильная точка внимания, и "
              "она обязана стоять на теме. Ролик без него теряет то, что "
              "зритель запомнит глазами")
        return 1

    print("  ЦВЕТНЫХ ПЯТЕН БОЛЬШЕ ОДНОГО:")
    for name, d in cvetnye:
        print(f"    · {name}: {d * 100:.2f}% кадра")
    print("  Глаз мечется между ними, и приём умирает. Оставить одно — то, "
          "которое стоит на теме ролика.")
    return 1


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
