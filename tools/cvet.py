#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
cvet.py — ГЕЙТ ЦВЕТНОГО ПРЕДМЕТА: одна цветная вещь в чёрно-белом кадре.

ПРИЁМ СТУДИИ. Ролик чёрно-белый, и ровно в одной локации живёт ОДИН цветной
ПРЕДМЕТ — вещь, а не подцветка кадра: сама локация остаётся чёрно-белой. Он не
украшение: в ч/б кадре единственное цветное пятно тянет глаз сильнее любой
композиции, и потому оно обязано стоять на теме ролика — как красная черта на
пороге в «Этике», буквально предмет разговора.

Движок этот приём уже держит: насыщенный пиксель ПЕРЕЖИВАЕТ монохромный проход
(`apply_monochrome` в `src/main.rs`: `mx − mn > 55` при `mx > 90`), и остаётся
единственным цветом в кадре. Здесь та же мерка, чтобы гейт и движок считали
цветом одно и то же.

ЧТО ПРОВЕРЯЕТСЯ

  · локация с цветным предметом в ролике РОВНО ОДНА. Две — глаз мечется,
    приём умирает;
    ноль — ролик теряет единственную точку, которую зритель запомнит глазами;
  · предмет маленький: не больше 3% кадра. Больше — это уже не вещь, а
    цветной кусок декорации, и он спорит с тушью. Цветным делается ПРЕДМЕТ,
    а не кадр: сама локация остаётся чёрно-белой целиком, без подцветки и
    тонировки.

ПОЧЕМУ СЧИТАЕТСЯ СВЯЗНОЕ ПЯТНО, А НЕ ОБЩАЯ ДОЛЯ. Первая версия ужимала растр
до 640×360 и считала долю ВСЕХ насыщенных пикселей, а нижний порог 0.2% я снял
с «шума». Обе мерки оказались неверны, и выяснилось это на первом же живом
предмете — красном магните на дверце холодильника в «Психологии еды».

  · Ужатие УБИВАЕТ малый предмет. Магнит в 166 пикселей на кадре 1280×720 при
    ужатии до 640×360 усредняется с чёрной дверцей и падает почти до нуля.
    Мерить надо в том разрешении, в котором лист лежит.
  · Долей нельзя отличить вещь от шума. Отдельные насыщенные пиксели по краю
    штриха рассыпаны по кадру, а предмет — ОДНО связное пятно. Поэтому берётся
    крупнейшая связная область; сумма разрозненных точек её не наберёт.
  · Порог 0.2% отвергал настоящие предметы. По этой мерке «шумом» числились
    счета на кухне (0.069% — одно связное пятно в 634 пикселя, то есть вещь) и
    столбы на дороге. Замер связностью показал: у ВСЕХ девяти цветных сетов
    каталога цвет собран в одно-два пятна, ни одного рассыпанного случая.

Нижний порог теперь 0.01% кадра — примерно сто пикселей при 720p, вещь около
десяти пикселей в поперечнике. Меньше — глаз не поймает даже на телефоне.

Замер по каталогу на день переделки: цвет несут девять сетов из ста семидесяти
с лишним, крупнейшее пятно — красная черта «Этики», 2.4% кадра; самое малое из
намеренных — магнит, 0.018%. Потолок 3% поставлен по черте с запасом.

Использование:
    python3 tools/cvet.py examples/lektorij/lozh.anim
"""

import argparse
import re
import sys
from collections import deque
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

IMPORT_SET = re.compile(r'import\s+set\s+\w+\s+from\s+"([^"]+)"')
POROG_DOLI = 0.03          # больше — уже не вещь, а декорация
POROG_SHUMA = 0.0001       # меньше — предмет не виден и на телефоне


def dolya_cveta(png):
    """Доля кадра под КРУПНЕЙШИМ связным цветным пятном, в родном разрешении."""
    import numpy as np
    from PIL import Image
    a = np.asarray(Image.open(png).convert("RGB"), dtype=int)
    mx, mn = a.max(2), a.min(2)
    m = (mx - mn > 55) & (mx > 90)
    if not m.any():
        return 0.0
    h, w = m.shape
    seen = np.zeros_like(m, bool)
    best = 0
    ys, xs = np.nonzero(m)
    for y0, x0 in zip(ys, xs):
        if seen[y0, x0]:
            continue
        q = deque([(y0, x0)])
        seen[y0, x0] = True
        s = 0
        while q:
            cy, cx = q.popleft()
            s += 1
            for dy in (-1, 0, 1):
                for dx in (-1, 0, 1):
                    ny, nx = cy + dy, cx + dx
                    if 0 <= ny < h and 0 <= nx < w and m[ny, nx] and not seen[ny, nx]:
                        seen[ny, nx] = True
                        q.append((ny, nx))
        best = max(best, s)
    return best / m.size


def main(argv):
    ap = argparse.ArgumentParser(description="Гейт цветного пятна")
    ap.add_argument("anim")
    a = ap.parse_args(argv)

    src = Path(a.anim)
    text = src.read_text(encoding="utf-8")
    cvetnye, bez_rastr = [], []
    for rel in IMPORT_SET.findall(text):
        svg = (src.parent / rel).resolve()
        png = svg.with_suffix(".png")
        if not png.exists():
            #  У части локаций растра рядом нет — они нарисованы вектором.
            #  Тогда цвет считать нечем, и это НЕ провал: гейт честно говорит,
            #  каких файлов не хватает, вместо того чтобы молча их пропустить.
            bez_rastr.append(svg.stem)
            continue
        d = dolya_cveta(png)
        if d > POROG_SHUMA:
            cvetnye.append((svg.stem, d))

    if bez_rastr:
        print(f"  цвет: без растра рядом (считать нечем): {', '.join(bez_rastr)}")

    if len(cvetnye) == 1:
        name, d = cvetnye[0]
        if d > POROG_DOLI:
            print(f"  ЦВЕТНОЙ ПРЕДМЕТ СЛИШКОМ БОЛЬШОЙ: {name} — {d * 100:.1f}% "
                  f"кадра при потолке {POROG_DOLI * 100:.0f}%. Это уже "
                  f"декорация, а не вещь: она спорит с тушью")
            return 1
        print(f"  цвет: один предмет — {name}, {d * 100:.2f}% кадра")
        return 0

    if not cvetnye:
        print("  ЦВЕТНОГО ПРЕДМЕТА НЕТ НИ В ОДНОЙ ЛОКАЦИИ. В ч/б ролике "
              "единственная цветная вещь — самая сильная точка внимания, и "
              "она обязана стоять на теме. Ролик без неё теряет то, что "
              "зритель запомнит глазами")
        return 1

    print("  ЦВЕТНЫХ ПРЕДМЕТОВ БОЛЬШЕ ОДНОГО:")
    for name, d in cvetnye:
        print(f"    · {name}: {d * 100:.2f}% кадра")
    print("  Глаз мечется между ними, и приём умирает. Оставить один — тот, "
          "который стоит на теме ролика.")
    return 1


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
