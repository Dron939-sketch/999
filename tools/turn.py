def small_turn():
    """ЧЕТВЕРТЬ ОБОРОТА (22.5°) — самый рабочий ракурс речи.

    Между анфасом и тремя четвертями. Рисунок плаща берётся АНФАСНЫЙ, а не
    torso_34: на 22.5° асимметрия кромок ещё в пределах толщины линии, а вот
    ширина уже заметно меньше — эллипс даёт 0.96 от анфаса. Ставить сюда
    полуоборотный рисунок значило бы показать спину там, где её не видно.
    Всё остальное — те же законы, взятые с половинной амплитудой, потому что
    sin 22.5° / sin 45° = 0.54:
      вынос маски      0.15 × 0.54 = 0.081 ширины плаща;
      наклон плеч      половина полуоборотного;
      сужение дальнего глаза и рта — по косинусу собственного угла.
    """
    d = math.radians(22.5)
    c, sn = math.cos(d), math.sin(d)
    sc = half(22.5) / 191.0 * 2
    return {"name": "povorot_pravo", "transition_duration": 0.3, "bones": {
        "cloak": {"part": "torso", "scale": [round(sc, 3), 1.0]},
        # ГОЛОВА ПОВЕРХ ПЛАЩА. z_order 1 (за корпусом) нужен там, где плечо
        # ОБЯЗАНО срезать низ маски: профиль, полуспина, спина. В ракурсах
        # лицом к камере зритель должен видеть голову ЦЕЛИКОМ — маска лежит
        # на чёрном, а не выглядывает из-за него. Я механически перенёс z_order
        # из профиля во все позы разворота, и подбородок с ртом уходили под
        # плечо: сперва лечил посадкой (76 → 62 → 30), хотя лечить надо было
        # порядок отрисовки.
        "head": {"scale": [0.96, round(1.02 * HEAD_Y, 4)], "z_order": 5, "offset": [
            (hx := head_x("torso", sc, RATIO_34 * sn / math.sin(math.radians(45)), 0.96)),
            52 + arc_drop("torso", sc, hx)]},
        # глаза против движения лица (см. quarter()), амплитуда по синусу:
        # 10.6 × sin22.5/sin45 = 5.7 от анфасного центра пары.
        # БЛИЖНИЙ ГЛАЗ НЕ СУЖАЕТСЯ — он смотрит почти прямо на зрителя, и на
        # 22.5° его ширина остаётся анфасной (0.85). Сужается только ДАЛЬНИЙ,
        # по косинусу собственного угла: 0.9 × cos22.5 = 0.831. Стояло 0.9,
        # то есть ближний был даже шире анфасного.
        "eye_left": {"part": "eye_left", "offset": [-42, -123],
                     "scale": [round(0.729 * c, 3), 1.07]},
        "eye_right": {"part": "eye_right", "offset": [10, -119],
                      "scale": [0.689, 0.98]},
        "mouth": {"offset": [-14, -56], "scale": [round(0.92, 3), 1.0]},
        # гнёзда по косинусу; дальняя рука уже за корпусом — на 22.5° из-за
        # плаща выходит только её нижняя треть, и это и есть признак поворота
        "upper_arm_right": {"offset": [socket_x("torso", sc, 9, +1), 9],
                            "scale": [1.06, 1.06], "z_order": 4},
        "upper_arm_left": {"offset": [socket_x("torso", sc, 17, -1), 17],
                           "scale": [0.94, 0.94], "z_order": 1},
        "thigh_left": {"offset": [round(-61.6 * c * 0.80), 172], "scale": [0.9, 0.94]},
        "shin_left": {"scale": [0.9, 0.94]},
        "thigh_right": {"offset": [round(29.6 * c), 172], "scale": [0.9, 1.06]},
        "shin_right": {"scale": [0.9, 1.06]},
    }}


def write():
    rig = json.loads(RIG.read_text(encoding="utf-8"))
    P = rig["poses"]
    made = []

    for pose, left in ((profile(), "bok_levo"), (quarter(), "chetvert_levo"),
                       (small_turn(), "povorot_levo")):
        P[pose["name"]] = pose
        P[left] = mirror(pose, left)
        made += [pose["name"], left]

    # СПИНА И ПОЛУСПИНА — МАСКА ЭТО НИЗКИЙ КУПОЛ, А НЕ ЯЙЦО.
    # Замер листа: маска анфас 70×106 (H/W 1.51), со спины 75×64 (H/W 0.85),
    # на полуспине 75×68. То есть сзади ширина РАСТЁТ до 1.07 от анфасной, а
    # высота ОБРУШИВАЕТСЯ до 0.60: виден верх черепа, а не овал лица. У нас
    # стояло 1.03×0.88 — купол выходил заметно выше эталонного.
    # Пивот головы у подбородка, поэтому сжатие по y роняет макушку; смещение
    # поднимаем на столько же, иначе купол утонет в плечах.
    sc34 = round(half(45) / CLOAK_34_INK * 2, 3)
    ps = P["polu_spina"]["bones"]
    ps["cloak"] = {"part": "torso_34", "scale": [-sc34, 1.0]}
    ps["head"]["scale"] = [1.07, round(0.84 * HEAD_Y, 4)]
    ps["head"]["offset"] = [head_x("torso_34", -sc34, RATIO_34, 1.07), 58]
    sp = P["spina"]["bones"]
    sp["head"]["scale"] = [1.07, round(0.83 * HEAD_Y, 4)]
    sp["head"]["offset"] = [head_x("torso", 1.092, 0.02, 1.07), 52]
    made += ["polu_spina", "spina"]

    # шаг в профиль: профиль + ноги из шаговой позы
    for base in ("bok_pravo", "bok_levo"):
        for step in ("shag_levoj", "shag_pravoj"):
            if step not in P:
                continue
            q = json.loads(json.dumps(P[base]))
            q["name"] = f"{base}_{step.split('_')[1]}"
            for leg in ("thigh_left", "thigh_right", "shin_left", "shin_right"):
                src = P[step]["bones"].get(leg)
                if src and q["bones"].get(leg, {}).get("scale") != [0, 0]:
                    keep = q["bones"].get(leg, {})
                    m = dict(src)
                    m["offset"] = keep.get("offset", m.get("offset"))
                    m["scale"] = keep.get("scale", m.get("scale"))
                    q["bones"][leg] = m
            P[q["name"]] = q
            made.append(q["name"])

    RIG.write_text(json.dumps(rig, ensure_ascii=False, indent=2), encoding="utf-8")
    return made


def measure():
    """Перезамер листа разворотов: ширина плаща и маски по клеткам."""
    try:
        from PIL import Image
        import numpy as np
    except ImportError:
        print("нужен Pillow + numpy"); return 1
    if not SHEET.exists():
        print(f"нет листа: {SHEET}"); return 1
    a = np.array(Image.open(SHEET).convert("L")); ink = a < 128
    cells = [(60, 240, "анфас"), (300, 480, "3/4"), (550, 740, "профиль"),
             (800, 990, "полуспина")]
    print(f"  {'клетка':<12}{'маска':>8}{'плащ':>8}{'плащ/анфас':>12}")
    base = None
    for x0, x1, name in cells:
        s = ink[60:520, x0:x1]
        hw = max((np.nonzero(s[y])[0].max() - np.nonzero(s[y])[0].min()
                  for y in range(100) if s[y].any()), default=0)
        ys, _ = np.nonzero(s)
        y = int(ys.min() + (ys.max() - ys.min()) * 0.5)
        r = np.nonzero(s[y])[0]
        cw = r.max() - r.min()
        base = base or cw
        print(f"  {name:<12}{hw:>8}{cw:>8}{cw/base:>12.2f}")
    return 0


def main(argv):
    ap = argparse.ArgumentParser()
    ap.add_argument("--write", action="store_true")
    ap.add_argument("--measure", action="store_true")
    a = ap.parse_args(argv)
    if a.measure:
        return measure()

    print(f"  плащ анфас {W:.0f}, профиль {D:.0f} ({D/W:.2f}), "
          f"три четверти {half(45)*2:.0f} ({half(45)*2/W:.2f})")
    print(f"  вынос головы: профиль {DEEP:.0f}, три четверти {DEEP_34:.0f}")
    if not a.write:
        return 0
    made = write()
    print(f"  записаны позы: {', '.join(made)}")
    return 0


