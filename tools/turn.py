def half(deg):
    t = math.radians(deg)
    return math.hypot(W / 2 * math.cos(t), D / 2 * math.sin(t))


def cloak_geom(part, sx):
    """(центр, ширина) силуэта плаща в системе кости `torso`.

    Считать вынос головы от ПИВОТА кости нельзя: ни один рисунок плаща не
    центрирован по нему (torso ink 0..191 при пивоте 110, torso_34 — 15..176).
    Поэтому «смещение головы» в позе значило разное для разных рисунков, а при
    зеркале ещё и меняло знак вместе с центром. Считаем от центра САМОГО
    силуэта — тогда одно число работает во всех ракурсах и не врёт в зеркале.
    """
    pts = outline(part)
    xs = [p[0] for p in pts]
    lo = (min(xs) - 110) * sx
    hi = (max(xs) - 110) * sx
    return (lo + hi) / 2, abs(hi - lo)


def head_x(part, sx, ratio, head_sx, head_ink_centre=HEAD_FRONT_OFF):
    """Смещение кости `head`, дающее нужную долю выноса маски."""
    c, w = cloak_geom(part, sx)
    return round(c + ratio * w - head_ink_centre * head_sx)


def arc_drop(part, sx, x_bone):
    """На сколько плечевая дуга ОПУСКАЕТСЯ под маской, смещённой в x_bone.

    Голова сидит НА плечевой дуге, а дуга к краям падает. Пока смещение шло по
    горизонтали при постоянной высоте, маска на стороне поворота повисала над
    линией плеча: разворот читался так, будто голову подняли, а не повернули.
    Считаем верхнюю кромку рисунка плаща под центром маски и под центром
    силуэта, разницу отдаём в смещение по y.
    """
    pts = outline(part)
    c, _ = cloak_geom(part, sx)

    def top_at(xb):
        xd = xb / sx + 110                      # обратно в систему рисунка
        near = [p[1] for p in pts if abs(p[0] - xd) < 9]
        return min(near) if near else None

    a, b = top_at(x_bone), top_at(c)
    return 0 if a is None or b is None else round(a - b)


# Насколько глубоко внутри силуэта сидят плечи В АНФАСЕ: гнездо рига делённое
# на полуширину плаща на своей высоте. Снято с рига, чтобы развороты не
# «раздвигали» плечи шире анфасных: посадка плеча — черта персонажа, а не
# следствие ракурса. Меняется ракурсом только КРОМКА, а доля остаётся.
INSET_NEAR = 0.74
INSET_FAR = 0.86


def socket_x(part, sx, y_bone, side, inset=None):
    """Гнездо руки на кромке плаща НА СВОЕЙ ВЫСОТЕ.

    Гнездо считалось от проекции точки тела (x₀·cos θ) — верно для круглого
    тела, но плащ у нас не цилиндр: у полуоборотного рисунка верх сужен, и
    спроецированное гнездо дальней руки оказывалось за кромкой на 16 единиц.
    Рука росла из воздуха. Плечо сидит ТАМ, ГДЕ КРОМКА, поэтому берём её из
    рисунка на высоте гнезда и отступаем внутрь на 6%.
    """
    pts = outline(part)
    yd = y_bone + 16                              # в систему рисунка
    xs = []
    for (x1, y1), (x2, y2) in zip(pts, pts[1:]):
        if (y1 - yd) * (y2 - yd) <= 0 and y1 != y2:
            xs.append(x1 + (yd - y1) / (y2 - y1) * (x2 - x1))
    if not xs:
        return 0
    lo, hi = (min(xs) - 110) * sx, (max(xs) - 110) * sx
    if lo > hi:
        lo, hi = hi, lo
    if inset is None:
        inset = INSET_NEAR if side > 0 else INSET_FAR
    mid = (lo + hi) / 2
    return round(mid + (hi - mid) * inset if side > 0 else mid + (lo - mid) * inset)


def mirror(pose, name):
    """Левый разворот: тот же набор костей, зеркальный torso."""
    q = json.loads(json.dumps(pose))
    q["name"] = name
    q["bones"]["torso"] = {"scale": [-TORSO_SCALE, TORSO_SCALE_Y]}
    return q


