#  Слово, впечатывающееся поверх кадра: ключ — НАЧАЛО ПЛАНА, сдвиг отмеряет до
#  самого слова. Ставится редко и только на удар — иначе приём стирается.
SLOVA = {
    130.23: ("САМИ?", 1.74),
    151.38: ("2 ИЗ 10", 0.63),
    432.54: ("6 НЕДЕЛЬ", 0.33),
    626.61: ("НЕТ", 0.69),
}

#  Пары поз персонажа: он молчит, и одинаковая фигура дважды читалась бы
#  заставкой.
POZY = [("vzglyad", "point"), ("razvel", "ladon_pusta")]

DOLGO = 9.0          # длиннее — добавляем тихий ход камеры
POLE = 0.048


def sobrat():
    sety = sorted({s for _, s, _ in BITY if s != S})
    L, A = [], None
    A = L.append
    A("// " + "=" * 74)
    A("//  ВИДЕОРЯД ЛЕКЦИИ 1 «Чью жизнь вы живёте» — ЦЕЛИКОМ.")
    A("//  Собран tools/lekciya1_polnaya.py — РУКАМИ НЕ ПРАВИТЬ.")
    A("//")
    A("//  Каждый кадр стоит на СВОЁМ СЛОВЕ из расшифровки записи")
    A("//  (lekciya-koleya-1-slova.json). Первая сборка вешала кадр на раздел,")
    A("//  и разделы стояли не на месте: она считалась по долям слов СТАТЬИ,")
    A("//  а запись — устная лекция. «Откуда настройки» уехало на минуту.")
    A("//")
    A("//  monochrome ВЫКЛЮЧЕН: запись называет цвет меток («пять красных»,")
    A("//  «одна зелёная»), и фильтр стёр бы сказанное вслух.")
    A("// " + "=" * 74)
    A('import character freeman from "../assets/characters/freeman_rig"')
    A('import set komnata from "../assets/sets/koleya-komnata.svg"')
    for s in sety:
        A(f'import set {s.replace("-", "_")} from "../assets/sets/{s}.svg"')
    A("")
    A("config {")
    for k, v in (("width", 1280), ("height", 720), ("fps", FPS),
                 ("background", "#d4d7cf"), ("monochrome", "false"),
                 ("snow", 0.10), ("on-twos", 2), ("line-boil", 0.55),
                 ("film-grain", 0.04), ("vignette", 0.10),
                 ("film-flicker", 0.02), ("gate-weave", 0.30),
                 ("film-scratch", 0.20), ("film-dust", 0.4),
                 ("light-angle", 45), ("form-shadow", 0.0), ("rim-light", 0.0),
                 ("ground-shadow", "true"), ("cast-shadow", 0.32)):
        A(f"    {k}: {v}")
    A("}")
    A("")

    granicy = [t for t, _, _ in BITY] + [KONEC]
    shov_n = 0
    for i, (t, setname, chto) in enumerate(BITY):
        kadrov = round((granicy[i + 1] - t) * FPS)
        d = (kadrov - 0.4) / FPS
        mm, ss = int(t // 60), t % 60
        A(f'// ── {mm}:{ss:05.2f} ({d:.2f}с) — «{chto}»')
        if setname == S:
            a, b = POZY[shov_n % len(POZY)]
            shov_n += 1
            A(f'scene "b{i:03d}_shov" (duration: 1s, set: komnata) {{')
            A("    transition static 0.10s")
            A("    place freeman at (0.50, 0.99) facing front on floor")
            A("    freeman scales 0.90 over 0.01s")
            A("    camera wide")
            A('    freeman pose "calm"')
            A("    wait 0.60s")
            A(f'    freeman pose "{a}"')
            A("    wait 1.40s")
            A(f'    freeman pose "{b}"')
            A("    wait 1.40s")
            A('    freeman pose "calm"')
            A(f"    wait {d - 0.10 - 0.01 - 0.60 - 1.40 - 1.40:.4f}s")
            A("}")
            A("")
            continue

        A(f'scene "b{i:03d}" (duration: 1s, set: {setname.replace("-", "_")}) {{')
        A("    transition static 0.10s")
        A("    camera two-shot")
        ost = d - 0.10
        slovo = None
        if t in SLOVA:
            slovo, kogda = SLOVA[t]
            A(f'    let w{i:03d} = text("{slovo}", 64) at (0.5, -2.0)')
            A(f"    wait {kogda:.2f}s")
            A(f"    w{i:03d} moves-to (0.500, 0.800) over 0.01s")
            ost -= kogda + 0.01
        if d > DOLGO:
            A(f"    camera pan-to (0.500, {0.5 - POLE:.3f}) over 0.01s")
            A(f"    camera pan-to (0.500, {0.5 + POLE:.3f}) "
              f"over {ost - 0.01 - (0.01 if slovo else 0):.4f}s ease-in-out")
        else:
            A(f"    wait {ost - (0.01 if slovo else 0):.4f}s")
        if slovo:
            A(f"    w{i:03d} moves-to (0.500, -2.000) over 0.01s")
        A("}")
        A("")
    return "\n".join(L)


def main():
    OUT.write_text(sobrat() + "\n", encoding="utf-8")
    granicy = [t for t, _, _ in BITY] + [KONEC]
    dl = [granicy[i + 1] - t for i, (t, _, _) in enumerate(BITY)]
    print(f"\n  ВИДЕОРЯД ЛЕКЦИИ 1 ЦЕЛИКОМ")
    print(f"  планов {len(BITY)}, смена в среднем каждые {KONEC/len(BITY):.1f}с")
    print(f"  самый длинный план {max(dl):.1f}с, самый короткий {min(dl):.2f}с")
    dolgie = [(t, d) for (t, _, _), d in zip(BITY, dl) if d > 20]
    for t, d in dolgie:
        print(f"  [ВНИМАНИЕ] {int(t//60)}:{t%60:05.2f} висит {d:.1f}с")
    print(f"  сеты: {len({s for _, s, _ in BITY})} разных")
    print(f"\n  записано: {OUT.relative_to(ROOT)}\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
