from pathlib import Path

from PIL import ImageDraw

sys.path.insert(0, str(Path(__file__).resolve().parent))
from risuem import TUSH, BUMAGA, W, H, holst, liniya, lomanaya, pryamoug, krug, \
    shtrih_ruka, shtrih_mashina, sohranit
from risuem_anketa import nadpis


def cennik(d, dd, cx, cy, sh=96, vys=64, cena="—", ww=11):
    """Ценник на крючке: карточка, дырка, крючок. Товара под ним нет."""
    liniya(d, (cx, cy - vys / 2 - 46), (cx, cy - vys / 2), w=6)
    krug(d, cx, cy - vys / 2 - 50, 13, w=6)
    pryamoug(d, (cx - sh / 2, cy - vys / 2, cx + sh / 2, cy + vys / 2), w=ww)
    krug(d, cx, cy - vys / 2 + 15, 6, w=5)
    nadpis(dd, (cx, cy + 6), cena, int(vys * 0.42), centr=True)


def polka_bez_tovara():
    """ПЕРВАЯ ЛОКАЦИЯ. На каждом месте висит цена, а взять нечего.

    ПУСТОТУ НАДО ОБЪЯВИТЬ, ИНАЧЕ ЕЁ НЕ ВИДНО. Первая проба вешала мелкие
    ценники на тонкие линии — читались коробочки на проволоке, и «товара нет»
    не прочитывалось: чтобы отсутствие било, место товара должно быть ОЧЕРЧЕНО.
    Поэтому под каждым ценником стоит пустой контур-подставка: рамка есть,
    внутри ничего.
    """
    im, d = holst(300)
    dd = ImageDraw.Draw(im)
    #  ПОЛКА С ГЛУБИНОЙ, И НИЧЕГО НА НЕЙ. Контур «места товара» под ценником
    #  читался подставкой, на которой ценник стоит, — отсутствие пропадало.
    #  Пустоту показывает сама полка: видна её ПОВЕРХНОСТЬ, длинная и голая,
    #  а ценники висят над ней на рейке и указывают в никуда.
    for y in (372, 622):
        liniya(d, (40, y - 54), (1240, y - 54), w=9)      # задняя кромка
        liniya(d, (40, y), (1240, y), w=20)               # передняя кромка
        liniya(d, (40, y + 20), (1240, y + 20), w=10)     # торец
        for xx in (40, 1240):
            liniya(d, (xx, y - 54), (xx, y), w=8)
    #  ЦЕННИК ВИСИТ ВЫШЕ ПОЛКИ, а не садится на неё: иначе читается «ценники
    #  стоят на полке», и пустая поверхность под ними пропадает — а она и есть
    #  всё высказывание кадра.
    for y, rejka, ceny in ((372, 130, ("799", "1 290", "2 400", "590")),
                           (622, 382, ("1 190", "450", "3 100"))):
        liniya(d, (40, rejka), (1240, rejka), w=10)       # рейка для ценников
        shag = 1200 // (len(ceny) + 1)
        for i, cena in enumerate(ceny):
            x = 40 + shag * (i + 1)
            liniya(d, (x, rejka), (x, rejka + 12), w=6)
            cennik(d, dd, x, rejka + 74, sh=170, vys=104, cena=cena, ww=15)
    liniya(d, (0, 690), (1280, 690), w=18)
    return sohranit(im, "polka-bez-tovara")


def kuhnya_schet():
    """ВТОРАЯ ЛОКАЦИЯ. Стол, на нём лента распечатки; ценник висит и здесь."""
    im, d = holst(301)
    dd = ImageDraw.Draw(im)
    pryamoug(d, (150, 470, 1130, 520), w=18)          # столешница
    for x in (240, 1040):
        liniya(d, (x, 520), (x, 690), w=16)
    #  ЛЕНТА — ПРЯМОУГОЛЬНИК СО СТРОКАМИ, А НЕ ЗАВИТУШКА. Первая проба рисовала
    #  ломаную с рукописным штрихом: читалось ёлочкой. Распечатка узнаётся по
    #  форме — узкий лист, ровные машинные строки, итог внизу под чертой.
    #  СТРОКИ РАЗНОЙ ДЛИНЫ, И ИХ МАЛО. Восемь плотных гребёнок подряд читались
    #  штриховкой, а не распечаткой: лист узнаётся по РИТМУ строк, а не по их
    #  количеству.
    pryamoug(d, (420, 110, 780, 470), w=14)
    for k, dl in enumerate((300, 240, 286, 200, 264)):
        liniya(d, (452, 172 + k * 46), (452 + dl, 172 + k * 46), w=11)
    liniya(d, (452, 402), (748, 402), w=13)
    nadpis(dd, (600, 416), "итого", 36, centr=True)
    cennik(d, dd, 960, 230, sh=150, vys=104, cena="₽", ww=14)
    liniya(d, (0, 690), (1280, 690), w=18)
    return sohranit(im, "kuhnya-schet")


def podezd_pochta():
    """ТРЕТЬЯ ЛОКАЦИЯ. Ряд почтовых ящиков; из каждого торчит бумага."""
    im, d = holst(302)
    dd = ImageDraw.Draw(im)
    #  Ящики КРУПНЕЕ и бумага торчит НАД щелью, а не рядом: иначе она читается
    #  уголком рисунка, а не письмом, которое не вынули.
    for r in range(2):
        for c in range(4):
            x, y = 120 + c * 220, 190 + r * 220
            pryamoug(d, (x, y, x + 180, y + 180), w=16)
            liniya(d, (x + 30, y + 128), (x + 150, y + 128), w=10)
            pryamoug(d, (x + 46, y + 30, x + 134, y + 122), w=10)
            for k in range(3):
                liniya(d, (x + 60, y + 52 + k * 22), (x + 120, y + 52 + k * 22), w=6)
    cennik(d, dd, 1120, 250, sh=150, vys=104, cena="—", ww=14)
    liniya(d, (0, 690), (1280, 690), w=18)
    return sohranit(im, "podezd-pochta")


def cennik_krupno():
    """ЧЕТВЁРТАЯ. Ценник крупным планом — под возврат якоря и финальный кадр."""
    im, d = holst(303)
    dd = ImageDraw.Draw(im)
    #  ЦЕННИК НЕ НАЗЫВАЕТ ЯКОРЬ. Первая проба ставила сюда «1000» — то есть
    #  картинка проговаривала «тысячу часов» и объясняла разрыв за зрителя.
    #  На ценнике стоит обычная цена; работает не число, а то, что под ценником
    #  пусто.
    cennik(d, dd, 640, 330, sh=520, vys=320, cena="2 400", ww=22)
    lomanaya(d, [(380, 620), (380, 520), (900, 520), (900, 620)], w=12, drozh=3.4)
    liniya(d, (0, 690), (1280, 690), w=18)
    return sohranit(im, "cennik-krupno")


def mera(imya, chelovek=0.55, back_y=0.50, front_y=0.96):
    """Мера человека и пол — без них локация не годится для говорящей сцены."""
    p = Path(f"examples/assets/sets/{imya}.surfaces.json")
    p.write_text(json.dumps({
        "floor": {"back_y": back_y, "front_y": front_y},
        "chelovek": chelovek,
        "_comment": ("Мера человека — доля высоты кадра, которую занимает фигура "
                     "у передней кромки пола. Ниже 0.5 локация для говорящей "
                     "сцены не годится (реестр §XL): фигура становится мелкой, "
                     "и мимика перестаёт читаться.")
    }, ensure_ascii=False, indent=2), encoding="utf-8")


if __name__ == "__main__":
    polka_bez_tovara(); mera("polka-bez-tovara")
