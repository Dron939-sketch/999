# полного прогона завода.
#
# Проверить машиной, КАК синтез прочтёт слово, нельзя — для этого его надо
# синтезировать. Зато можно не наступать дважды: список пополняется тем, на
# чём обожглись, и слово чинится заменой, а не разметкой.
