# СЛОВА, НА КОТОРЫХ СИНТЕЗ СТАВИТ СВОЁ УДАРЕНИЕ И ЗНАК U+0301 НЕ ПОМОГАЕТ.
# Разметка ударения обычно работает, но не всегда: у части слов модель держит
# ударение жёстко и размеченную гласную игнорирует. Заметить это можно только
