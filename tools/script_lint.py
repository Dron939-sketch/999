# СЛОВА, КОТОРЫЕ БЕЗ ЗНАКА U+0301 СИНТЕЗ ЧИТАЕТ НЕ ТАК, А СО ЗНАКОМ — ТАК.
# Отличие от MISSTRESS выше: там разметка не помогает и слово надо ЗАМЕНЯТЬ,
# здесь достаточно её поставить. Ловим ровно тот случай, на котором обожглись
# в «Влиянии»: слово написано голым, автор не подумал про ударение, и ошибку
# слышно только на готовом ролике — то есть после полного прогона завода.
#
# Проверка работает на простом свойстве: размеченное «индю<U+0301>шка» НЕ
# содержит подстроки «индюшка», знак разрывает её. Значит голый поиск находит
# только неразмеченные вхождения, и ложных срабатываний на исправленном тексте
# нет. Список пополняется тем, что услышали.
# СПИСОК ПУСТ, И ЭТО РЕЗУЛЬТАТ, А НЕ НЕДОДЕЛКА. Всё, что сюда попадало —
# «индю́шка», «хорька́», «на́смерть», — студия услышала с чужим ударением,
# и каждое пришлось не размечать, а заменять (см. MISSTRESS выше). Три из трёх:
# похоже, движок озвучки эту разметку просто не читает. Проверить машиной
# нельзя — надо синтезировать и услышать.
#
# Механизм оставлен на случай слова, на котором знак себя покажет: тогда строка
# сюда, и гейт проследит, чтобы разметку не потеряли. Но писать реплики в
# расчёте на неё нельзя — надёжен только выбор слова.
UNMARKED = []

# ОБРАЗ — ОДИН ПРЕДМЕТ, КОТОРЫЙ ДЕРЖИТ РОЛИК. Правило написано после разбора
# пяти роликов: дважды подряд студия говорила «непонятно, о чём речь» про
# ключевое слово ролика («что за кнопка?»), и оба раза причина была одна —
# ТЕРМИН ОБЪЯСНЯЛСЯ ТЕРМИНОМ. Слово вводили определением («кнопка — это
# короткий сигнал»), а не предметом, который видно в кадре.
#
# Что сработало на самом деле: велосипед в «Истории религий», банка на
# подоконнике в «Дистанции», чайник в «Эмоциях». Общее у них одно — это ВЕЩЬ,
# она стоит в кадре с первой секунды, попадает в перечисление и возвращается в
# финале с другим знаком. Такой образ объясняет механизм без единого термина и
# заодно даёт шутку, растущую из темы, а не приклеенную к ней.
#
# Гейт проверяет ровно проверяемое: строка `ОБРАЗ:` в шапке есть, названное в
# ней слово встречается в репликах НЕ МЕНЕЕ ДВУХ РАЗ (посадка и возврат) и
# хотя бы раз — во второй половине ролика. Красоту образа машина не оценит,
# но «образа нет вообще» и «образ назван один раз и забыт» ловит.
IMAGE = re.compile(r"\*\*ОБРАЗ:\*\*\s*([^\n—-]+)", re.I)

# ПРОБЛЕМА / РЕШЕНИЕ / ШУТКА — три строки, без которых интро не интро.
#
# Правило студии, записанное дословно: «каждый курс — это решение какой-то
# проблемы; ролик — оголение проблемы с указанием на решение; и в интро должен
# быть юмор относительно НЕ-решения — для тех, кто не хочет решать».
#
# Отсюда три обязательные строки в шапке. Машина не оценит, та ли это проблема
# и смешно ли, — но проверит, что автор их СФОРМУЛИРОВАЛ. Разница огромная:
# ролик, у которого проблема не названа словами, всегда расползается в
# рассуждение, а шутка, не привязанная к отказу решать, оказывается приклеенной.
PROBLEM = re.compile(r"\*\*ПРОБЛЕМА:\*\*\s*(\S[^\n]*)", re.I)
SOLUTION = re.compile(r"\*\*РЕШЕНИЕ:\*\*\s*(\S[^\n]*)", re.I)
JOKE_DECL = re.compile(r"\*\*ШУТКА:\*\*\s*(\S[^\n]*)", re.I)
# ГДЕ СТОИТ ШУТКА. Объявление обязано назвать реплику: «Шутка стоит на подъёме
# (VO-9)». Без адреса проверить её нечем — гейт не умеет опознать смешное на
# слух и не должен пытаться (на угадывании смысла по словам уже обжигались).
JOKE_ADDR = re.compile(r"\*\*ШУТКА:\*\*[^\n]*(?:\n(?!\n)[^\n]*)*", re.I)
JOKE_VO = re.compile(r"VO-?(\d+)")
# ПРЕДЕЛ — вторая половина шутки: момент, когда не-решение перестаёт работать.
# Именно он превращает насмешку в аргумент: смеются не над человеком, а над
# способом, у которого назван срок годности.
JOKE_PREDEL = re.compile(
    r"(работает\s+(?:ровно\s+)?до|хватает\s+(?:ровно\s+)?до|пока\s+не|"
    r"до\s+(?:тех\s+пор|первого|первой)|ровно\s+до|стоит\s+целый|стоит\s+"
    r"(?:секунд|минут|вечер|день))", re.I)

BEATS = ["ХУК", "ПУЛЕМ", "РАЗВОРОТ", "ВЗЛ", "ЖАЛО"]
# Приветствие — необязательный бит ПЕРЕД хуком. Если оно есть, хуку даётся
# больше времени: приветствие само держит зрителя, потому что назначает роль.
HELLO = "ПРИВЕТСТВИЕ"
FINALE_OK = re.compile(r"(\?|!|…|\.\.\.)\s*[»\"]?\s*$")
# высокий и сниженный регистры — их столкновение и есть стиль (§4 SCRIPT-FREEMAN)
HIGH = re.compile(r"(свобод|сознани|достоинств|вечност|смысл|истин|бытие|судьб|душ)", re.I)
LOW = re.compile(r"(жр[ая]|жу[ёе]|мяс|шкур|брюх|лент[аы]|диван|жвачк|стад|быдл|дыши|доживать|тухн)", re.I)

# --- драматургия и драмеди (DRAMATURGIYA.md) --------------------------------
# Шапка сценария объявляет сквозную мысль и конфликт ДО реплик. Это не
# формальность: ролик без единства действия набирает второй тезис и распухает
# за потолок в 60с, а монолог без препятствия превращается в проповедь.
THESIS = re.compile(r"^\s*(?://\s*)?(?:\*\*)?СКВОЗНАЯ(?:\*\*)?\s*:", re.I | re.M)
CONFLICT = re.compile(r"^\s*(?://\s*)?(?:\*\*)?КОНФЛИКТ(?:\*\*)?\s*:", re.I | re.M)
# Смеховые маркеры финала. Ищутся ТОЛЬКО в последней реплике: шутка в финале
# обнуляет ставку, зритель уходит развлечённым, а не выбитым (§13).
JOKE = re.compile(r"(ха-ха|хе-хе|шучу|шутка|прикол|смешно|ржа|анекдот|\)\))", re.I)


def parse(path):
    """Достаём из таблицы VO пары (бит, реплика)."""
    rows = []
    for line in Path(path).read_text(encoding="utf-8").splitlines():
        if not line.strip().startswith("|"):
            continue
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if len(cells) < 3 or cells[0].startswith(("#", "---", ":--")):
            continue
        if not re.match(r"VO-?\d", cells[0], re.I):
            continue
        # ранние сценарии писались без колонки «Бит формулы» — тогда её нет,
        # и проверки по битам честно провалятся, а не молча пропустятся
        beat, text = (cells[2], cells[3]) if len(cells) >= 4 else ("", cells[2])
        # ремарка режиссёра в курсиве — не произносится, из текста убираем
        remark = " ".join(re.findall(r"\*\((.*?)\)\*", text))
        spoken = re.sub(r"\*\(.*?\)\*", "", text).strip()
        spoken = spoken.strip("«»\"").strip()
        # Ударения (U+0301 после ударной гласной) — разметка для синтеза, а не
        # часть слова. Гейт ищет слова по списку («ты», «вы», бытовое/высокое),
        # и размеченный текст мимо этих списков проходил: у ролика с honest
        # разметкой падало «обращение к зрителю» и «столкновение регистров»
        # при неизменном тексте. Снимаем знак ПЕРЕД любыми проверками.
        # ...но проверке «размечено ли ударение» нужен текст ДО снятия знака,
        # иначе она видит голое слово там, где автор всё разметил, и валит
        # исправленный сценарий. Держим оба вида: `text` — для смысловых
        # проверок, `text_raw` — для проверки самой разметки.
        spoken_raw = spoken
        spoken = spoken.replace(ACCENT, "")
        rows.append({"n": cells[0], "time": cells[1], "beat": beat,
                     "text": spoken, "text_raw": spoken_raw, "remark": remark,
                     # была ли реплика в «ёлочках» — ровно тот признак, по
                     # которому voiceover.py выбирает ячейку для синтеза
                     "quoted": "«" in text and "»" in text,
                     # сколько ячеек строки закавычено: больше одной — строка
                     # неоднозначна для сборщика озвучки (см. проверку ниже)
                     "quotes": sum(1 for c in cells if "«" in c and "»" in c)})
    return rows


def first_time(cell):
    """Начало реплики в секундах из «0:03.5–0:05.2»."""
    m = re.search(r"(\d+):(\d+(?:\.\d+)?)", cell)
    return int(m.group(1)) * 60 + float(m.group(2)) if m else None


def hits(rows, raw=""):
    """Список проверок: (вес, пройдено, название, что не так).

    `raw` — исходный текст файла: шапка сценария (СКВОЗНАЯ/КОНФЛИКТ) живёт вне
    таблицы реплик, а проверять её надо (DRAMATURGIYA.md §1, §3).
    """
    out = []
    if not rows:
        return [(100, False, "таблица VO", "не нашёл ни одной строки VO-N")]
    text_all = " ".join(r["text"] for r in rows)
    beats_all = " ".join(r["beat"] for r in rows).upper()
    first, last = rows[0], rows[-1]
    # ПОДПИСЬ-КОЛЬЦО НЕ СЧИТАЕТСЯ ФИНАЛОМ. Ролики уходят в ленту, где они
    # зациклены, и последняя реплика серии — не удар, а сшивка: «Так, идём
    # дальше. Лекторий Мейстера, курс лекций номер N» плюс тот же жест, что и в
    # первых секундах. Она ОБЪЯВЛЯЕТ СЛЕДУЮЩЕЕ, поэтому кончается точкой, и
    # требовать от неё вопроса или обрыва бессмысленно.
    #
    # Драматургический финал — реплика перед подписью, её и проверяем.
    ring = "ПОДПИС" in last["beat"].upper() or "КОЛЬЦ" in last["beat"].upper()
    if ring and len(rows) > 1:
        last = rows[-2]

    out.append((10, bool(ADDRESS.search(first["text"])), "обращение к зрителю в первой реплике",
                "первая фраза не адресована лично («ты/вы») — зритель остаётся наблюдателем"))
    out.append((10, not WARMUP.search(first["text"]) or bool(GREETING.search(first["text"])),
                "нет разогрева",
                "первая фраза начинается с представления или «сегодня поговорим»"))

    missing = [b for b in BEATS if b not in beats_all]
    out.append((15, not missing, "все биты формулы на месте",
                f"нет битов: {', '.join(missing)}" if missing else ""))

    # порядок битов: ХУК раньше ПУЛЕМЁТА, РАЗВОРОТ раньше ВЗЛЁТА, ЖАЛО последним
    idx = {b: next((i for i, r in enumerate(rows) if b in r["beat"].upper()), None)
           for b in BEATS}
    seq = [idx[b] for b in BEATS if idx[b] is not None]
    out.append((10, seq == sorted(seq), "порядок битов",
                "биты идут не в порядке формулы — кривая энергии ломается"))

    # длина ударной фразы: считаем по предложениям, медиана ядра ≤7 слов
    sents = [s for s in re.split(r"[.!?…]+", text_all) if s.strip()]
    lens = [len(s.split()) for s in sents if s.split()]
    med = statistics.median(lens) if lens else 99
    out.append((10, med <= 7, f"медиана ударной фразы {med:.0f} слов (норма ≤7)",
                "фразы длинные — рублёный ритм оригинала теряется"))

    # РУБЛЕНОСТЬ КАК МАНЕРА. Замечание студии: «слишком много рубленых фраз,
    # они плохо слышатся». Претензия точная и обратная предыдущей проверке:
    # медиана ≤7 слов гонит фразу вниз, и если гнать без остановки, монолог
    # превращается в очередь коротких ударов, между которыми нечем дышать.
    # Оригинал так не звучит: у него ядро 3–7 слов, но длинные периоды на
    # разгоне обязательны, и рубленость — ПРИЁМ, собранный в одном месте
    # (пулемёт), а не общий тон.
    #
    # Меряем долю предложений в три слова и короче. У забракованной версии
    # «Привязанности» их было 62% — то есть почти весь текст; у переписанной
    # 25%, и четыре из пяти стоят подряд, образуя тот самый пулемёт. Порог 35%
    # разводит эти два случая с запасом и не мешает ни одному из готовых
    # роликов серии.
    chop = [n for n in lens if n <= 3]
    share = len(chop) / len(lens) if lens else 0
    out.append((10, share <= 0.35,
                f"рубленых фраз {share:.0%} (норма ≤35%)",
                "почти весь текст — короткие удары; между ними нечем дышать. "
                "Рубленость собирается в пулемёт, остальное ведётся периодами "
                "со связками (SCRIPT-FREEMAN §2, §4)"))

    # триада: три и более коротких предложения подряд (пулемёт)
    triad = any(all(len(s.split()) <= 3 for s in sents[i:i + 3]) for i in range(len(sents) - 2))
    out.append((10, triad, "есть пулемётная триада",
                "нет серии из трёх коротких ударов подряд"))

    out.append((8, bool(HIGH.search(text_all) and LOW.search(text_all)),
                "столкновение регистров",
                "нет пары «высокое + бытовое» — текст в одном регистре"))

    # ЧТО УЙДЁТ В ГОЛОС. Реплика опознаётся по «ёлочкам» — и если их нет,
    # синтез озвучит СОСЕДНЮЮ ячейку. Так уже случилось: в таблице появилась
    # пятая колонка «Локация / ход», и голос зачитал вслух режиссёрскую
    # ремарку про то, куда персонаж идёт. Гейт проверяет то же, что читает
    # voiceover.py, — чтобы ошибка ловилась в сценарии, а не в готовом ролике.
    unquoted = [r["n"] for r in rows if not r.get("quoted", True)]
    out.append((16, not unquoted,
                "реплики в «ёлочках»",
                f"без кавычек: {', '.join(unquoted)} — в озвучку уйдёт "
                f"соседняя ячейка (ремарка, локация), а не текст"))

    # ЁЛОЧКИ РОВНО ОДИН РАЗ В СТРОКЕ. Обратная беда к предыдущей и куда
    # злее: реплика закавычена правильно, но закавычено ЕЩЁ ЧТО-ТО в той же
    # строке — и сборщик берёт не ту ячейку. Так в готовый ролик уехало «зал,
    # у „по́лок“» вместо «Лекторий. Университет Мейстера…»: режиссёрская
    # колонка получила своё закавыченное слово, и озвучка честно его прочла.
    # Ошибка молчаливая — mp3 есть, липсинк сходится, длина совпадает, — и
    # ловится только ухом на готовом файле. Поэтому ловим здесь.
    twice = [r["n"] for r in rows if r.get("quotes", 1) > 1]
    out.append((16, not twice,
                "ёлочки только у реплики",
                f"по две закавыченные ячейки: {', '.join(twice)} — сборщик "
                f"возьмёт первую, но соседняя закавыченная колонка означает, "
                f"что строка читается неоднозначно; кавычки внутри служебных "
                f"колонок замени обычными"))

    # тайм-якоря 3–7–21
    t_first = first_time(first["time"])
    has_hello = HELLO in beats_all
    # Считаем по ПЕРВОЙ реплике: она обязана прозвучать в первые 7 секунд.
    # Если открывает фирменное приветствие, самому хуку даётся до 14 секунд —
    # но не больше: приветствие держит внимание, а не заменяет удар.
    hook_row = next((r for r in rows if "ХУК" in r["beat"].upper()), None)
    t_hook = first_time(hook_row["time"]) if hook_row else None
    limit = 14.0 if has_hello else 7.0
    ok_first = t_first is not None and t_first <= 7.0
    ok_hook = t_hook is not None and t_hook <= limit
    out.append((7, ok_first and ok_hook,
                f"первая реплика ≤7с, хук ≤{limit:.0f}с"
                + (" (с фирменным приветствием)" if has_hello else ""),
                f"первая реплика на {t_first}с, хук на {t_hook}с — зритель уже ушёл"))

    # ИНСТАГРАМ: ДВЕ СЕКУНДЫ НА ЗАХВАТ, ВОСЕМЬ НА КРЮЧОК.
    #
    # Ролики уезжают в ленту, где решение «смотреть или листать» принимается за
    # первые две секунды и пересматривается к восьмой. Прежние пороги (первое
    # слово ≤7 с) писались под страницу курса, где зритель уже пришёл смотреть.
    # В ленте он не пришёл — его надо поймать.
    #
    # Меряется по таймкодам VO-таблицы: первое слово должно прозвучать в первые
    # две секунды, а бит ХУК — закончиться к восьмой. Молчаливая заставка на
    # четыре секунды в ленте означает пролистанный ролик.
    hook_end = None
    if hook_row:
        m = re.findall(r"(\d+):(\d+(?:\.\d+)?)", hook_row["time"])
        if len(m) >= 2:
            hook_end = int(m[1][0]) * 60 + float(m[1][1])
    ok_2s = t_first is not None and t_first <= 2.0
    ok_8s = hook_end is not None and hook_end <= 8.0
    out.append((8, ok_2s and ok_8s, "лента: первое слово ≤2с, хук закрыт ≤8с",
                (f"первое слово на {t_first}с — в ленте это уже пролистано; "
                 if not ok_2s else "")
                + (f"хук кончается на {hook_end}с вместо 8" if not ok_8s else "")))
    turn = next((r for r in rows if "РАЗВОРОТ" in r["beat"].upper()), None)
    t_turn = first_time(turn["time"]) if turn else None
    out.append((5, t_turn is not None and 14.0 <= t_turn <= 28.0, "перелом в окне 14–28с",
                f"разворот на {t_turn}с — вторая перезагрузка внимания не туда"
                if t_turn else "бита РАЗВОРОТ нет"))

    out.append((5, not SUMMING.search(text_all), "нет подведения итогов",
                "есть «подводя итог»/«таким образом» — мораль проговорена, глубина схлопывается"))
    out.append((5, bool(FINALE_OK.search(last["text"])), "финал — удар, а не точка",
                "последняя реплика заканчивается ровной точкой: нет вопроса, вызова или обрыва"))

    words = set(re.findall(r"[а-яё]+", text_all.lower()))
    burnt = [(w, alt) for w, alt in MISSTRESS.items() if w in words]
    out.append((6, not burnt, "нет слов с известным сбоем ударения",
                "; ".join(f"«{w}» синтез прочтёт с неверным ударением, знак U+0301 "
                          f"его не переубеждает — замени на «{alt}»"
                          for w, alt in burnt)))

    # Слово сверяется ЦЕЛИКОМ и по снятой разметке, а знак ищется в исходном
    # написании. Иначе «хорька́» ловится как голое «хорька»: знак стоит после
    # последней буквы, подстрока слова остаётся целой, и гейт валит уже
    # исправленный сценарий (проверено на нём же).
    raw_all = " ".join(r.get("text_raw", r["text"]) for r in rows)
    naked, hints = set(), set()
    for w in re.findall(r"[а-яёА-ЯЁ" + ACCENT + r"]+", raw_all):
        bare = w.replace(ACCENT, "").lower()
        for pat, hint in UNMARKED:
            if re.fullmatch(pat, bare) and ACCENT not in w:
                naked.add(w)
                hints.add(hint)
    naked, hints = sorted(naked), sorted(hints)
    out.append((6, not naked, "слова с подвижным ударением размечены",
                "; ".join(f"«{w}»" for w in naked)
                + " — без знака U+0301 синтез прочтёт по-своему. Правильно: "
                + "; ".join(hints) if naked else ""))

    out.append((4, ring, "есть подпись-кольцо для ленты",
                "последняя реплика — не подпись: в ленте ролик зациклен, и без "
                "сшивки зритель на втором круге видит шов. Нужна реплика вида "
                "«Так, идём дальше. Лекторий Мейстера, курс лекций номер N» с тем "
                "же жестом, что и в первых секундах"))

    bad = [name for name, pat in FORBIDDEN.items() if re.search(pat, text_all, re.I)]
    out.append((5, not bad, "нет стоп-приёмов",
                f"сработали запреты PSYCHOLOGY.md §5: {', '.join(bad)}" if bad else ""))

    # --- драматургия и драмеди (DRAMATURGIYA.md) ----------------------------
    # Проверяется ТОЛЬКО структура. Конфликт, ставка, качели заряда и общий
    # корень шутки словарём не меряются — в DRAMATURGIYA.md против них честно
    # написано «гейта нет». Гейт, угадывающий смысл по словам, врёт увереннее,
    # чем помогает: завод это уже проходил на гейте забытой руки.
    out.append((5, bool(THESIS.search(raw)), "объявлена сквозная мысль",
                "в шапке нет строки «СКВОЗНАЯ:» — единство действия не задано, "
                "ролик наберёт второй тезис (DRAMATURGIYA.md §3)"))
    out.append((5, bool(CONFLICT.search(raw)), "объявлен конфликт",
                "в шапке нет строки «КОНФЛИКТ:» — нет препятствия, монолог "
                "станет проповедью (DRAMATURGIYA.md §1)"))

    # ТРИАДЫ С ОТКЛОНЕНИЕМ (§10) ЗДЕСЬ НЕТ — И ЭТО РЕШЕНИЕ, А НЕ ПРОПУСК.
    # Отклонение третьего элемента семантическое: «Утро. Работа. Лента. Сон.» —
    # перечисление, «Утро. Работа. Лента. Всё.» — удар, и обе триады состоят из
    # односложных предложений одинаковой длины. Любой счётный признак (слова,
    # буквы) обе строки не различает и потому валит ХОРОШИЕ сценарии: проверка
    # заваливала два ролика из шести, не показав в них ни одного дефекта.
    # Закон остаётся в силе и проверяется человеком по чек-листу §III.9.

    # --- ПРОБЛЕМА / РЕШЕНИЕ / ШУТКА ------------------------------------------
    for rx, name, why in (
        (PROBLEM, "названа проблема",
         "в шапке нет строки «ПРОБЛЕМА:» — курс решает задачу, и ролик обязан "
         "её ОГОЛИТЬ. Без формулировки интро расползается в рассуждение"),
        (SOLUTION, "указано решение",
         "в шапке нет строки «РЕШЕНИЕ:» — ролик оголяет проблему и УКАЗЫВАЕТ на "
         "решение; без этого зритель уходит с болью и без выхода"),
        (JOKE_DECL, "объявлена шутка про НЕ-решение",
         "в шапке нет строки «ШУТКА:» — юмор в интро идёт про тех, кто решать не "
         "хочет. Шутка, не привязанная к отказу решать, всегда приклеенная"),
    ):
        out.append((7, bool(rx.search(raw)), name, why))

    # --- ОБРАЗ: вещь вместо термина -----------------------------------------
    im = IMAGE.search(raw)
    if not im:
        out.append((8, False, "объявлен образ",
                    "в шапке нет строки «ОБРАЗ:» — ролик будет объяснять термин "
                    "термином. Назови ОДНУ вещь, которая стоит в кадре, попадает "
                    "в перечисление и возвращается в финале"))
    else:
        # Берём из объявления самое длинное слово: «банка на подоконнике» → «подоконнике»
        # не годится, поэтому ищем по основе первого существительного (4+ буквы).
        words = [w for w in re.findall(r"[а-яё]{4,}", im.group(1).lower())]
        stem = words[0][:-2] if words else ""
        hits_ = len(re.findall(stem, text_all.lower())) if stem else 0
        half = " ".join(r["text"] for r in rows[len(rows) // 2:]).lower()
        late = bool(stem) and stem in half
        out.append((8, hits_ >= 2 and late, f"образ «{im.group(1).strip()}» работает",
                    f"образ объявлен, но в репликах встречается {hits_} раз(а)"
                    + ("" if late else " и ни разу во второй половине")
                    + ": он должен быть посажен в начале и вернуться в финале"))

    out.append((5, not JOKE.search(last["text"]), "финал не на шутке",
                "последняя реплика — шутка: ставка обнулена, зритель уходит "
                "развлечённым, а не выбитым (DRAMATURGIYA.md §13)"))

    # --- ШУТКА: УСТРОЙСТВО, А НЕ НАЛИЧИЕ (DRAMATURGIYA §14) ------------------
    #
    # Строка «ШУТКА:» в шапке проверялась на существование — и этого мало.
    # Требование студии устроено так: курс РЕШАЕТ проблему, ролик её оголяет,
    # показывает решение, и ПОСЛЕ решения смеётся над теми, кто решение не
    # берёт, а продолжает делать то, что проблему и создаёт.
    #
    # Отсюда три проверяемых признака, снятых с двух шуток, которые работают:
    #
    #   «Эмоции»: заткнуть свисток тряпкой | работает, пока не понадобится чаю
    #   «Логика»: брать дверь побольше     | работает ровно до вопроса «почему»
    #
    #   1. АДРЕС. Объявление называет реплику (VO-N). Без него гейту нечего
    #      проверять, а автору нечего держать в голове.
    #   2. МЕСТО. Шутка стоит ПОСЛЕ решения (бит ВЗЛЁТ) и ДО жала. Шутка
    #      раньше решения смеётся над тем, чего зритель ещё не знает, и
    #      читается как насмешка над ним самим.
    #   3. ПРЕДЕЛ. В шутке назван момент, когда не-решение перестаёт работать.
    #      Это и делает её аргументом: смешон не человек, а способ с назначенным
    #      сроком годности.
    #
    # Чего гейт НЕ проверяет: смешно ли. Словарём не меряется, и гейт,
    # угадывающий смысл по словам, врёт увереннее, чем помогает (§IV).
    decl = JOKE_ADDR.search(raw)
    addr = JOKE_VO.findall(decl.group(0)) if decl else []
    out.append((6, bool(addr), "шутка называет, где стоит",
                "строка «ШУТКА:» не указывает реплику — добавь «стоит на "
                "подъёме (VO-N)». Без адреса шутку нечем проверить"))
    if addr:
        n = int(addr[0])
        beats = [r["beat"].upper() for r in rows]
        vzlet = next((i for i, b in enumerate(beats, 1) if "ВЗЛ" in b), None)
        zhalo = next((i for i, b in enumerate(beats, 1) if "ЖАЛО" in b), None)
        posle = vzlet is None or n > vzlet
        do_zhala = zhalo is None or n < zhalo
        out.append((7, posle and do_zhala,
                    "шутка стоит после решения и до жала",
                    f"шутка объявлена в VO-{n}, взлёт в VO-{vzlet}, жало в "
                    f"VO-{zhalo} — юмор про НЕ-решение идёт ПОСЛЕ решения, "
                    f"иначе он смеётся над тем, чего зритель ещё не знает"))
        # `n` в строке таблицы — текст вида «VO-9», а не число.
        row = next((r for r in rows
                    if (m_ := re.search(r"(\d+)", r["n"])) and int(m_.group(1)) == n),
                   None)
        joke_text = (row["text"] if row else "") + " " + (decl.group(0) if decl else "")
        out.append((6, bool(JOKE_PREDEL.search(joke_text)),
                    "в шутке назван предел не-решения",
                    "шутка не говорит, ДО КАКОГО МОМЕНТА способ работает. Без "
                    "предела это насмешка над человеком; с пределом — цена "
                    "способа («работает ровно до того, как…»)"))
    return out


def main(argv):
    ap = argparse.ArgumentParser()
    ap.add_argument("files", nargs="*")
    ap.add_argument("--all", action="store_true", help="все *-VO.md в examples/")
    a = ap.parse_args(argv)

    files = a.files or (sorted(glob.glob("examples/**/*-VO.md", recursive=True))
                        if a.all else [])
    if not files:
        raise SystemExit("нечего проверять: укажи файл или --all")

    worst = 0
    for f in files:
        rows = parse(f)
        checks = hits(rows, Path(f).read_text(encoding="utf-8"))
        score = sum(w for w, ok, _, _ in checks if ok)
        total = sum(w for w, _, _, _ in checks)
        score = round(100 * score / total) if total else 0
        worst = max(worst, 0 if score >= GATE else 1)
        print(f"\n  ГЕЙТ СЦЕНАРИЯ: {Path(f).name}   реплик: {len(rows)}")
        for w, ok, name, why in checks:
            print(f"    [{'OK  ' if ok else 'ПРОВАЛ'}] {name}" + (f"\n             → {why}" if not ok and why else ""))
        print(f"    ИТОГО {score}/100 — {'взят' if score >= GATE else f'НЕ ВЗЯТ (порог {GATE})'}")
    print("\n  Не проверяется машиной и остаётся на человеке: выстреливает ли\n"
          "  притча на развороте, не подменена ли глубина красивыми словами,\n"
          "  честен ли хук по отношению к содержанию ролика. Из драматургии —\n"
          "  названа ли ставка в единицах жизни зрителя (§2), меняется ли заряд\n"
          "  между соседними битами (§6), растут ли смех и боль из одного корня\n"
          "  (§8) и не остаётся ли зритель в финале внизу по статусу (§11).\n")
    return worst


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
