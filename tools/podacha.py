# Явные метки в ремарке — режиссёр отменяет умолчание.
RE_TEMP = re.compile(r"темп\s*[:=]?\s*([\d]+[.,]?\d*)\s*слог", re.I)
RE_REG = re.compile(r"регистр\s*[:=]?\s*([а-яё]+)", re.I)
# Старая запись «темп 0.88» (множитель) — держим ради совместимости, но
# переводим в цель: множитель к целевому темпу бита, а не к длине файла.
RE_TEMP_STARY = re.compile(r"темп\s*[×xх*]?\s*([01][.,]\d+)")

# Границы растяжки. Ниже 0.80 голос плывёт, выше 1.30 съедаются согласные —
# именно на этом сгорел прежний потолок 1.58. Если цель не достаётся в этих
# границах, виноват ТЕКСТ (его слишком много), и чинить надо текст.
K_MIN, K_MAX = 0.80, 1.32


# ДОБАВКИ поверх регистра. Регистр отвечает на вопрос «что должно произойти со
# зрителем», а это — физика произнесения: шёпот бывает и вовлекающим, и
# приговором. Поэтому они не заменяют регистр, а ложатся сверху.
