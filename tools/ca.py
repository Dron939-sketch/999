#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
ca.py — КОМУ ЭТОТ РОЛИК И УЗНАЁТ ЛИ ОН ПЕРВЫЙ КАДР.

ЗАЧЕМ. Разрыв шаблона — половина метода: внимание цепляет не яркое, а
несовместимое. Но несовместимость существует только относительно ЧЕГО-ТО.
Лампа, горящая в безымянной комнате, — просто рисунок; лампа, горящая на
кухне, которую зритель узнал как СВОЮ, — неправильность, и он останавливается.
Рыбе нужна вода, в которой её узнают. Пока первая локация «вообще комната»,
разрыву не от чего отталкиваться, и приём тратится впустую.

Отсюда правило: у курса определяется зритель, и первая локация ролика берётся
ИЗ ЕГО ДНЯ. Не «кухня» вообще, а та кухня, в которой этот человек стоит утром;
не «офис» вообще, а тот стол, за которым он сидит.

ЧТО ПРОВЕРЯЕТСЯ. Четыре вещи — по шапке VO, раскадровке и папке сетов:

  1. В шапке объявлена строка `**ЦА:**` — кто смотрит курс. Одной фразой и
     конкретно: занятие, обстановка, в которой он живёт.
  2. В шапке объявлена строка `**ПЕРВАЯ ЛОКАЦИЯ:**` — имя сета в обратных
     кавычках и объяснение, чем он узнаваем именно для этого зрителя.
  3. Названный сет ДЕЙСТВИТЕЛЬНО стоит первой сценой раскадровки. Без этой
     сверки объявление живёт своей жизнью: локацию меняют по ходу сборки, а
     строка в шапке остаётся от прошлого замысла и врёт.
  4. Файл сета лежит в `examples/assets/sets/`. Если его нет — сборка НЕ идёт,
     и гейт говорит, где искать промт. Локация под зрителя не берётся из того,
     что уже есть в репозитории: под неё пишется промт (`<id>-IMAGE-PROMPTS.md`),
     студия рисует по нему картинку и кладёт в репозиторий. Завод ждёт файл, а
     не подбирает похожий: похожий — это и есть «вообще комната».

ЧЕГО ГЕЙТ НЕ УМЕЕТ. Он не скажет, верно ли определён зритель, — это работа
человека. Но он ловит самый частый способ не определить его вовсе: ответ
«все». «Каждый», «любой», «все мы» в строке ЦА — это не аудитория, а отказ
выбирать, и первая локация после такого ответа всегда получается ничьей.

Использование:
    python3 tools/ca.py examples/lektorij/stress-VO.md
"""

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

CA = re.compile(r"^\s*\*\*ЦА:?\*\*\s*:?\s*(.+?)\s*$", re.M | re.I)
UZN = re.compile(r"^\s*\*\*УЗНАВАНИЕ:?\*\*\s*:?\s*(.+?)\s*$", re.M | re.I)
#  Опись имущества вместо положения: если фраза узнавания держится на названии
#  помещения, метафоры нет — есть документальный кадр.
POMESCHENIE = re.compile(r"\b(офис|кухн\w*|комнат\w*|кабинет\w*|зал\w*|"
                         r"квартир\w*|цех\w*|склад\w*|коридор\w*)\b", re.I)
LOK = re.compile(r"^\s*\*\*ПЕРВАЯ ЛОКАЦИЯ:?\*\*\s*:?\s*`([^`]+)`\s*(.*)$", re.M | re.I)
SCENA = re.compile(r'^\s*scene\s+"[^"]+"\s*\([^)]*set:\s*(\w+)', re.M)
IMPORT = re.compile(r'^\s*import\s+set\s+(\w+)\s+from\s+"([^"]+)"', re.M)

#  «Все» — не аудитория. Список короткий намеренно: он ловит не стиль, а отказ
#  выбирать, и растить его до словаря синонимов не надо.
VSE = re.compile(r"\b(все|всех|всем|каждый|каждому|любой|любому|кто угодно|"
                 r"все мы|всякий)\b", re.I)

MINIMUM = 40      # знаков в строке ЦА: короче — это ярлык, а не зритель


def proverit(vo_path):
    vo = Path(vo_path).resolve()
    anim = vo.with_name(vo.stem.replace("-VO", "") + ".anim")
    t = vo.read_text(encoding="utf-8")
    out = []

    m = CA.search(t)
    ca = m.group(1).strip() if m else ""
    out.append(("зритель курса объявлен строкой «ЦА»", bool(ca),
                "в шапке нет строки «**ЦА:**» — не сказано, кто это смотрит, "
                "и первая локация выбиралась ни для кого"))
    if ca:
        out.append(("зритель назван конкретно, а не «все»",
                    not VSE.search(ca) and len(ca) >= MINIMUM,
                    f"«{ca[:70]}» — это отказ выбирать, а не аудитория. "
                    f"Занятие, возраст, обстановка дня: локацию узнаю́т по "
                    f"обстановке, а не по диагнозу" if VSE.search(ca)
                    else f"строка короче {MINIMUM} знаков — это ярлык, а не "
                         f"зритель, и узнавать в кадре нечего"))

    m = UZN.search(t)
    uzn = m.group(1).strip() if m else ""
    out.append(("названо, ЧТО зритель узнаёт в первом кадре", bool(uzn),
                "в шапке нет строки «**УЗНАВАНИЕ:**» — не сказано, свою беду "
                "или своё стремление зритель видит в кадре. Без этого локация "
                "выходит документальной: место опознано, положение — нет"))
    if uzn:
        out.append(("узнавание названо положением, а не помещением",
                    not POMESCHENIE.search(uzn) and len(uzn) >= 25,
                    f"«{uzn[:70]}» — это опись имущества, а не положение. "
                    f"Правило проверки: фраза обязана складываться БЕЗ названия "
                    f"помещения («всё стекается к одному столу» — годится, "
                    f"«офис вечером» — нет)"))

    m = LOK.search(t)
    lok, pochemu = (m.group(1).strip(), m.group(2).strip()) if m else ("", "")
    out.append(("первая локация объявлена и обоснована",
                bool(lok) and len(pochemu) >= 20,
                "в шапке нет строки «**ПЕРВАЯ ЛОКАЦИЯ:** `сет` — чем узнаётся»"
                if not lok else
                "локация названа, но не сказано, чем она узнаётся этим "
                "зрителем — а это и есть весь смысл строки"))

    if lok:
        #  КАРТИНКА ЛИБО ЕСТЬ, ЛИБО ЗАВОД ЖДЁТ. Промт пишется заранее и лежит
        #  рядом с роликом; пока файла сета нет, сборка не идёт.
        fajl_sveta = ROOT / "examples/assets/sets" / f"{lok}.svg"
        promty = anim.with_name(anim.stem + "-IMAGE-PROMPTS.md")
        out.append((f"картинка локации «{lok}» лежит в репозитории",
                    fajl_sveta.exists(),
                    f"нет файла examples/assets/sets/{lok}.svg — жду картинку. "
                    f"Промт для неё: {promty.relative_to(ROOT) if promty.exists() else 'ЕЩЁ НЕ НАПИСАН, напиши его первым'}"))

    if lok and anim.exists():
        a = anim.read_text(encoding="utf-8")
        imena = dict(IMPORT.findall(a))
        scены = SCENA.findall(a)
        pervaya = scены[0] if scены else None
        fajl = Path(imena.get(pervaya, "")).stem if pervaya else ""
        out.append((f"первой сценой стоит именно «{lok}»", fajl == lok,
                    f"в шапке объявлена «{lok}», а первая сцена идёт на "
                    f"«{fajl or '—'}»: объявление отстало от раскадровки"))
    return out


def main(argv):
    if len(argv) < 2:
        print("укажи VO-файл"); return 2
    plohih = 0
    print("\n  ЗРИТЕЛЬ И ПЕРВЫЙ КАДР\n")
    for f in argv[1:]:
        print(f"    {Path(f).name}:")
        for imya, ok, pochemu in proverit(f):
            print(f"      [{'OK  ' if ok else 'ПРОВАЛ'}] {imya}")
            if not ok:
                print(f"               → {pochemu}")
                plohih += 1
    print()
    if plohih:
        print(f"  Провалов: {plohih}. Первый кадр обязан быть его кадром.")
    else:
        print("  Зритель назван, и ролик открывается его локацией.")
    return 1 if plohih else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
