def bez_rulya():
    """«По колее едешь без руля: усилия не требует, вопросов не задаёт»."""
    im, d = holst(71)
    dd = ImageDraw.Draw(im)
    liniya(d, (40, 250), (1240, 250), w=16)
    for x_niz, x_verh in ((300, 566), (980, 714)):
        liniya(d, (x_niz, 720), (x_verh, 250), w=22)
    krug(d, 640, 470, 120, w=20)
    krug(d, 640, 470, 34, w=14, zaliv=TUSH)
    for a in range(0, 360, 90):
        import math
        r = math.radians(a)
        liniya(d, (640 + 34 * math.cos(r), 470 + 34 * math.sin(r)),
               (640 + 118 * math.cos(r), 470 + 118 * math.sin(r)), w=14)
    lomanaya(d, [(470, 330), (810, 610)], w=18)
    lomanaya(d, [(810, 330), (470, 610)], w=18)
    return sohranit(im, "lek1v-bez-rulya")


