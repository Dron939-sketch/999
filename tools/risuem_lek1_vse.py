def obraz(k):
    """Четыре приметы обычной жизни — по одной, как их называют."""
    im, d = holst(60 + k)
    dd = ImageDraw.Draw(im)
    for i in range(4):
        if i >= k:
            continue
        x = 76 + i * 292
        pryamoug(d, (x, 130, x + 268, 500), w=16)
        if i == 0:                       # календарь пять на два
            for r in range(3):
                for c in range(5):
                    pryamoug(d, (x + 30 + c * 44, 200 + r * 68,
                                 x + 64 + c * 44, 250 + r * 68), w=8,
                             zaliv=TUSH if r < 2 else None)
        elif i == 1:                     # море и солнце
            krug(d, x + 196, 210, 46, w=12)
            for r in range(4):
                liniya(d, (x + 26, 330 + r * 38), (x + 242, 330 + r * 38),
                       w=11, drozh=5.0)
        elif i == 2:                     # дом
            domik(d, x + 134, 456, 196, 186, ww=13)
        else:                            # мангал и дым
            pryamoug(d, (x + 52, 372, x + 216, 428), w=13, zaliv=TUSH)
            for sd in (-1, 0, 1):
                lomanaya(d, [(x + 134 + sd * 48, 350), (x + 118 + sd * 48, 300),
                             (x + 148 + sd * 48, 250)], w=10)
            for sd in (-1, 1):
                liniya(d, (x + 134 + sd * 62, 428), (x + 134 + sd * 78, 486), w=11)
        nadpis(dd, (x + 134, 546), OBRAZ[i], 46, centr=True)
    return sohranit(im, f"lek1v-obraz-{k}")


