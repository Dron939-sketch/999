def vycherk(skolko):
    """«Он вычёркивал по строчке и смотрел, что сломается»."""
    im, d = holst(80 + skolko)
    dd = ImageDraw.Draw(im)
    stroki = ["дом побольше", "вещей посолиднее", "статус поприличнее",
              "работа круглый год", "отпуск как у всех"]
    pryamoug(d, (200, 90, 1080, 640), w=18)
    for i, s in enumerate(stroki):
        y = 150 + i * 100
        nadpis(dd, (256, y), s, 48)
        if i < skolko:
            liniya(d, (236, y + 32), (1040, y + 32), w=13)
    return sohranit(im, f"lek1v-vycherk-{skolko}")


