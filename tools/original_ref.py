"""
original_ref.py — ЗАМЕР ОРИГИНАЛА: пропорции и пластика с настоящих кадров.

ЗАЧЕМ. Всё, чем мы до сих пор мерили похожесть, замкнуто на нас самих: болван
берёт глубину фигуры с НАШЕГО рисунка профиля, приёмщик разворота сравнивает
наши ракурсы друг с другом. Если исходный рисунок врёт, вся система врёт
согласованно и незаметно. Внешнего эталона не было — а он всё это время лежал
в корне репозитория: три ролика Мистера Фримена, семь с половиной минут
настоящей анимации 1280×720.

ЧТО МЕРЯЕТСЯ. По кадрам, где фигура видна целиком:

  · ГЛУБИНА/ШИРИНА. Фигура за ролик поворачивается во все стороны. Значит
    ширина плаща, нормированная на рост, гуляет от анфаса (максимум) до
    профиля (минимум). Их отношение и есть искомое k — снятое с настоящего
    тела, а не выведенное из нашего рисунка.
  · ПРОПОРЦИИ МАСКИ: ширина и высота в долях роста.
  · ПЛАСТИКА: доля силуэта, меняющаяся между соседними кадрами. Это грубая
    мера «живости»: у рисованной вручную фигуры она заметно выше, чем у
    подменяемых плоских деталей.

КАК ОТБИРАЮТСЯ КАДРЫ. В оригинале полно планов без фигуры (текст, предметы,
чёрный экран) и обрезанных сверхкрупных. Берём кадр, только если:
  1. есть крупная тёмная компонента — тело;
  2. внутри неё есть замкнутая светлая область — маска;
  3. компонента не касается верхней и нижней кромки кадра — иначе фигура
     обрезана и рост неизвестен, а все доли считаются от роста.
Третье условие отсекает как раз те сверхкрупные планы, на которых пропорции
посчитались бы от куска.

═══════════════════════════════════════════════════════════════════════════
ВНИМАНИЕ: ПЕРВАЯ ВЕРСИЯ ЭТОГО ФАЙЛА ВЫДАЛА НЕВЕРНОЕ ЧИСЛО, И ПО НЕМУ УСПЕЛИ
ИСПОРТИТЬ ПЕРСОНАЖА. Читать целиком, прежде чем доверять выводу.
═══════════════════════════════════════════════════════════════════════════

Прибор сообщал «маска оригинала = 0.287 роста, наша 0.363 — голова крупнее на
четверть». По этому числу голову уменьшили в 1.75 раза (0.375 → 0.257 роста),
и персонаж перестал быть похож на себя. Число было неверным.

ЧТО СЛОМАНО В ОТБОРЕ КАДРОВ. Показать это оказалось просто: если нарисовать
на принятых кадрах рамку «фигуры» и рамку «маски», видно, что прибор мерит:

  · кадр со столом на весь низ — стол сливается с фигурой в одну тёмную
    компоненту, «рост» получается вдвое больше настоящего, и маска выходит
    0.167 роста;
  · кадр с фигурой внутри нарисованной рамки-кляксы — «маской» становится вся
    рамка, и получается 0.986;
  · кадр с поднятой над головой рукой — рука входит в габарит, «рост» растёт,
    доля маски падает.

Годных кадров при этом всего два десятка на семь минут, поэтому такой мусор
не тонет в статистике, а ТАЩИТ МЕДИАНУ ВНИЗ. Отсюда и 0.287.

ЧТО НА САМОМ ДЕЛЕ. С починенным отбором (компонента не крупнее 30% площади
кадра, фигура выше половины кадра, ширина не больше 0.75 роста, маска в верхней
четверти фигуры И ВНУТРИ ЕЁ ГАБАРИТА ПО X) тем же прибором:

    маска / рост      оригинал                    риг
    высота            0.344 (кв.25 0.289 …        0.375
                             кв.75 0.381)

И ГЛАВНОЕ — ЭТО НЕ ОДНО ЧИСЛО, А ПОЛОСА, и полоса настоящая. На контактном
листе видно два разных плана: в одном фигура с доской даёт 0.29, в другом
стоящая фигура даёт 0.38. Оригинал рисован от руки покадрово, и художник менял
пропорцию от сцены к сцене. Требовать от рига попадания в точку — значит
требовать точности, которой нет в источнике.

Риг с его 0.375 лежал ВНУТРИ полосы, у верхнего края. Правка увела его на
0.257 — ЗА полосу целиком. То есть голова в риге была правильная с самого
начала, и правки не требовала вовсе.

УРОК, КОТОРЫЙ ДОРОЖЕ ЧИСЛА. Прибор, меряющий похожесть, обязан показывать НЕ
ТОЛЬКО ИТОГ, НО И ТО, ЧТО ОН ПРИНЯЛ ЗА ФИГУРУ. Пять минут на контактный лист
с нарисованными рамками — и ошибка видна сразу; без него правдоподобное число
уходит в работу и тянет за собой правку рига, откат голденов и полдня разбора.
Флаг `--sheet` теперь такой лист печатает; гонять его при каждом изменении
порогов.

НЕ ИЗМЕРИЛОСЬ — ГЛУБИНА К ШИРИНЕ. Замысел был: ширина плаща гуляет от анфаса к
профилю, отношение краёв даст k. Не работает по двум причинам, обе выяснились
только на кадрах:
  · угол поворота в кадре неизвестен, и профиль неотличим от приседа — обе позы
    дают узкую строку;
  · у оригинала плащ КОРОЧЕ нашего, и строка «45% роста» попадает у него на
    ноги, а у нас на плащ. Мы мерили разные вещи и сравнивали результаты.
Первый прогон выдал «анфас 2.062» — плащ вдвое шире роста, — и это было видно
как абсурд. Второй, с ужесточённым отбором, выдал правдоподобные 0.245, и вот
это опаснее: число выглядит разумным и всё равно неверно.

НЕ ИЗМЕРИЛОСЬ — ВЫСОТА ПОДОЛА. Детектор ищет резкое падение ширины и на нашей
фигуре ловит конец разведённых рук вместо края плаща: «ширина плаща» вышла
0.019 роста. На оригинале (0.835) число похоже на правду, но сравнивать не с
чем, пока наша сторона мерится неверно.

Вывод для следующего захода: величины, не зависящие от позы (маска), меряются
по видео; всё, что зависит от ракурса или от разметки частей, требует либо
листа разворотов, либо ручной пометки кадров по углам.

Использование:
    python3 tools/original_ref.py "Mr. Freeman, part 00 ... .mp4"
    python3 tools/original_ref.py *.mp4 --fps 4
"""

import argparse
import subprocess
import sys
import tempfile
from pathlib import Path

import numpy as np
from PIL import Image

sys.path.insert(0, str(Path(__file__).resolve().parent))
from karta import label  # noqa: E402

INK = 90            # порог «это тушь»
LIGHT = 190         # порог «это светлое» (маска, фон)
MIN_BODY = 0.004    # тело — компонента не мельче этой доли площади кадра


def flood_bg(light):
    """Светлое, связанное с краем кадра, — это фон, а не маска."""
    lab = label(light)
    if not lab.max():
        return np.zeros_like(light, bool)
    edge = set(lab[0]) | set(lab[-1]) | set(lab[:, 0]) | set(lab[:, -1])
    edge.discard(0)
    return np.isin(lab, list(edge)) if edge else np.zeros_like(light, bool)


def measure(g):
    """Кадр → замер фигуры или None, если фигуры целиком нет."""
    h, w = g.shape
    dark = g < INK
    lab = label(dark)
    if not lab.max():
        return None
    sizes = [(int((lab == i).sum()), i) for i in range(1, lab.max() + 1)]
    n, i = max(sizes)
    if n < MIN_BODY * h * w:
        return None
    body = lab == i
    ys, xs = np.nonzero(body)
    y0, y1 = int(ys.min()), int(ys.max())
    x0, x1 = int(xs.min()), int(xs.max())
    # обрезанная фигура: рост неизвестен, доли от него считать нельзя
    if y0 <= 1 or y1 >= h - 2:
        return None
    hh = y1 - y0 + 1
    # ФИГУРА, А НЕ ФИГУРА-СО-СТОЛОМ. Тёмная компонента, занимающая треть кадра,
    # это уже не персонаж: в кадрах оригинала он то и дело касается чёрного
    # предмета (стол, полотнище, крыло), они сливаются в одну компоненту, и
    # «рост» удваивается. Доля маски тогда падает вдвое, а кадр выглядит
    # законным. Именно такие кадры утянули медиану с 0.35 на 0.287.
    if n > 0.30 * h * w:
        return None
    # ПЛАН НЕ ОБЩЕ-ОБЩИЙ. На мелкой фигуре маска — десяток пикселей, и её
    # граница гуляет на треть собственного размера.
    if hh < 0.50 * h:
        return None

    # маска — замкнутое светлое внутри фигуры
    # МАСКА ИЩЕТСЯ В ВЕРХНЕЙ ЧЕТВЕРТИ ФИГУРЫ, А НЕ ПО ВСЕМУ КАДРУ. Прежняя
    # версия брала САМУЮ КРУПНУЮ замкнутую светлую область и ловила то карман
    # фона между рукой и корпусом, то внутренность нарисованной рамки на весь
    # кадр (тот самый замер 0.986). Голова у Фримена всегда наверху — это и
    # есть надёжный признак, а «самая крупная» им не является.
    light = g > LIGHT
    inner = light & ~flood_bg(light)
    lab_w = label(inner)
    mask, best = None, None
    for j in range(1, lab_w.max() + 1):
        yy, xx = np.nonzero(lab_w == j)
        if len(yy) <= 40:
            continue
        if (yy.min() - y0) / hh > 0.25:
            continue
        # МАСКА ЛЕЖИТ ВНУТРИ ФИГУРЫ, А НЕ РЯДОМ С НЕЙ. Без этого условия
        # прибор брал в маски нарисованный рядом костёр: замкнутая светлая
        # область, в верхней части кадра, крупная — все прежние признаки
        # сходились, и кадр давал 0.73 вместо 0.38. Видно это только на
        # контактном листе, числом — никак.
        if xx.min() < x0 or xx.max() > x1:
            continue
        if best is None or len(yy) > best[0]:
            best = (len(yy), j, yy, xx)
    if best is not None:
        _, _, my, mx = best
        mask = (int(mx.max() - mx.min() + 1), int(my.max() - my.min() + 1))
    if mask is None:
        return None

    # ЭТО ВООБЩЕ ФИГУРА? Первый прогон дал «анфас 2.062», то есть плащ вдвое
    # шире роста, — в отбор лезли широкие тёмные пятна со светлой дырой:
    # телефон, мясорубка, надписи. Три условия, каждое от конкретного мусора:
    # (проверка «маска в верхней части тела» теперь стои́т в самом отборе маски
    # выше и жёстче: верхняя ЧЕТВЕРТЬ, а не половина)
    # 0.75 роста, а не «выше, чем шире»: с рукой, поднятой над головой, габарит
    # растёт вверх и доля маски падает, хотя голова не менялась.
    if (x1 - x0 + 1) > 0.75 * hh:             # руки не раскинуты, поза стоячая
        return None
    if not 0.12 <= mask[0] / hh <= 0.45:      # голова правдоподобной доли роста
        return None

    # ШИРИНА ПЛАЩА БЕЗ РУК. Руки-ниточки приклеиваются к корпусу и добавляют
    # к ширине свой размах — тот же изъян, что чинили в приёмщике разворота.
    # Берём самый длинный СПЛОШНОЙ тёмный отрезок строки, а не габарит.
    row = y0 + int(hh * 0.45)
    idx = np.flatnonzero(body[row])
    if not len(idx):
        return None
    cuts = np.flatnonzero(np.diff(idx) > 1)
    starts = np.concatenate(([0], cuts + 1))
    ends = np.concatenate((cuts, [len(idx) - 1]))
    cw = int((idx[ends] - idx[starts]).max()) + 1
    return {"h": hh, "cloak_w": cw, "mask_w": mask[0], "mask_h": mask[1],
            "body": body, "fig_box": (x0, y0, x1, y1),
            "mask_box": (int(mx.min()), int(my.min()),
                         int(mx.max()), int(my.max()))}


def contact_sheet(shots, out):
    """Лист принятых кадров с нарисованными рамками фигуры и маски.

    БЕЗ ЭТОГО ЛИСТА ПРИБОРУ ВЕРИТЬ НЕЛЬЗЯ. Именно он показывает, что прибор
    посчитал фигурой: стол, слипшийся с плащом, или рамку-кляксу вместо лица.
    Числа при таком мусоре выглядят правдоподобно, картинка — нет.
    """
    from PIL import ImageDraw
    if not shots:
        return
    shots = shots[:: max(1, len(shots) // 12)][:12]
    tw, th = 320, 180
    sheet = Image.new("RGB", (tw * 4, th * ((len(shots) + 3) // 4)), (255, 255, 255))
    for k, (g, fig, msk, val) in enumerate(shots):
        im = Image.fromarray(g).convert("RGB")
        dr = ImageDraw.Draw(im)
        dr.rectangle(fig, outline=(230, 0, 0), width=2)
        dr.rectangle(msk, outline=(0, 140, 255), width=2)
        im = im.resize((tw, th))
        ImageDraw.Draw(im).text((6, 6), f"{val:.3f}", fill=(230, 0, 0))
        sheet.paste(im, ((k % 4) * tw, (k // 4) * th))
    sheet.save(out)
    print(f"  контактный лист принятых кадров → {out}")


def scan(video, fps, limit=None, shots=None):
    rows, prev, churn = [], None, []
    with tempfile.TemporaryDirectory() as d:
        subprocess.run(["ffmpeg", "-y", "-loglevel", "error", "-i", str(video),
                        "-vf", f"fps={fps},scale=640:360", f"{d}/f%05d.png"],
                       check=True)
        files = sorted(Path(d).glob("f*.png"))
        if limit:
            files = files[:limit]
        for f in files:
            g = np.asarray(Image.open(f).convert("L"))
            m = measure(g)
            if m is None:
                prev = None
                continue
            if shots is not None:
                shots.append((g, m["fig_box"], m["mask_box"], m["mask_h"] / m["h"]))
            rows.append(m)
            if prev is not None and prev.shape == m["body"].shape:
                churn.append(float((prev ^ m["body"]).sum()) /
                             max(prev.sum() + m["body"].sum(), 1))
            prev = m["body"]
    return rows, churn


def main(argv=None):
    ap = argparse.ArgumentParser(description="Замер оригинала Фримена")
    ap.add_argument("videos", nargs="+")
    ap.add_argument("--fps", type=float, default=3.0)
    ap.add_argument("--sheet", metavar="PNG", default=None,
                    help="контактный лист принятых кадров с рамками фигуры и "
                         "маски — без него числам верить нельзя (см. шапку)")
    args = ap.parse_args(argv)

    allrows, allchurn = [], []
    shots = [] if args.sheet else None
    for v in args.videos:
        rows, churn = scan(v, args.fps, shots=shots)
        print(f"  {Path(v).name[:46]:46} годных кадров {len(rows):4}")
        allrows += rows
        allchurn += churn
    if not allrows:
        sys.exit("ни одного кадра с целой фигурой — проверь пороги")

    rel = np.array([r["cloak_w"] / r["h"] for r in allrows])
    mw = np.array([r["mask_w"] / r["h"] for r in allrows])
    mh = np.array([r["mask_h"] / r["h"] for r in allrows])
    # Границы ряда берём квантилями, а не min/max: одиночный кадр с рукой
    # поперёк корпуса или с обрезанным подолом задрал бы край.
    lo, hi = float(np.quantile(rel, 0.05)), float(np.quantile(rel, 0.95))

    print(f"\n  ОРИГИНАЛ — {len(allrows)} кадров с целой фигурой\n")
    print(f"  ширина плаща / рост:  профиль {lo:.3f} … анфас {hi:.3f}")
    print(f"  ГЛУБИНА / ШИРИНА = {lo / hi:.3f}")
    print(f"     у нас в риге:     0.700  (turn.py, константа SIDE)")
    print(f"     расхождение:      {lo / hi - 0.700:+.3f}")
    print(f"\n  маска / рост:  ширина {np.median(mw):.3f}   высота {np.median(mh):.3f}")
    print(f"     разброс высоты: кв.25 {np.quantile(mh, 0.25):.3f} … "
          f"кв.75 {np.quantile(mh, 0.75):.3f}")
    print(f"     риг (замер тем же прибором): высота 0.375")
    print(f"  маска: высота/ширина {np.median(mh) / np.median(mw):.3f}")
    if args.sheet:
        contact_sheet(shots, args.sheet)
    else:
        print("\n  Числам верить рано: прогони с --sheet и посмотри, что прибор\n"
              "  принял за фигуру. По неповеренному числу уже уменьшали голову.")
    if allchurn:
        print(f"\n  пластика: между соседними кадрами меняется "
              f"{np.median(allchurn) * 100:.1f}% силуэта")
    print()
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
