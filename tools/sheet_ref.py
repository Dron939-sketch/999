#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
sheet_ref.py — ЗАМЕР ЛИСТА-ЭТАЛОНА: числа с референса, а не с нашей же фигуры.

ЗАЧЕМ. Объёмный болван (`proxy3d.py`) держится на одном числе — отношении
глубины к ширине. Сейчас оно снимается с НАШЕЙ ЖЕ позы `bok_pravo`, то есть с
рисунка профиля, который сам под подозрением. Если он врёт, болван врёт ровно
так же и незаметно: ошибка разъедется по всем девяти ракурсам и будет выглядеть
согласованной. Проверять подозреваемого им самим нельзя.

Этот файл меряет лист-эталон: находит на нём фигуры, снимает высоту, ширину по
строкам и высотные отметки. Дальше отношение глубины к ширине берётся с
референса, а не выводится из наших поз.

ЧТО МОЖНО И ЧЕГО НЕЛЬЗЯ БРАТЬ С ЛИСТА. Персонаж на присланных листах — не наш:
другая голова, другой подол, лапы вместо ступней. Поэтому:

  · МОЖНО — отношения и доли: глубина/ширина, высота плеча и подола в долях
    роста. Они переносятся между близкими по конструкции фигурами.
  · НЕЛЬЗЯ — абсолютные размеры и координаты. И тем более нельзя брать
    подписанные на картинке цифры: на присланном «чертеже с размерами» оба
    глаза стоят в одной точке (4.5, 16.5), межзрачковое расстояние 2.31 при
    диаметре глаза 5, а в выноске кисти углы 450° и 459°. Это картинка чертежа,
    а не чертёж. Мерить надо пиксели, а не читать выноски.

Отношение глубины к ширине считается ТОЛЬКО когда анфас и профиль сняты одним
листом в одном масштабе. Смешивать профиль с чужого листа и наш анфас нельзя —
у фигур разные пропорции, и частное будет ни о чём.

Использование:
    python3 tools/sheet_ref.py лист.png                 # что на листе найдено
    python3 tools/sheet_ref.py лист.png --figures 3     # три вида на листе
    python3 tools/sheet_ref.py трёхвидовый.png --k      # глубина/ширина
"""

import argparse
import sys
from pathlib import Path

import numpy as np
from PIL import Image

sys.path.insert(0, str(Path(__file__).resolve().parent))
from karta import label  # noqa: E402

INK = 100          # порог «это тушь» на белом листе
MIN_FRAC = 0.35    # фигурой считаем компоненту не ниже этой доли высоты листа
ROW_45 = 0.45      # строка замера ширины — та же, что у приёмщика разворота


def figures(path, want=None):
    """Силуэты фигур на листе, слева направо. [(x0,y0,x1,y1, маска)].

    Лист несёт не только фигуры: подписи, выноски, отдельно вынесенные детали.
    Фигурой считаем высокую компоненту — деталь и буква ниже трети листа.
    """
    g = np.asarray(Image.open(path).convert("L"))
    dark = g < INK
    lab = label(dark)
    out = []
    for i in range(1, lab.max() + 1):
        m = lab == i
        ys, xs = np.nonzero(m)
        if not len(ys):
            continue
        h = ys.max() - ys.min() + 1
        if h < MIN_FRAC * g.shape[0]:
            continue
        out.append((int(xs.min()), int(ys.min()), int(xs.max()), int(ys.max()), m))
    out.sort(key=lambda r: r[0])
    if want is not None:
        out = sorted(out, key=lambda r: -(r[3] - r[1]))[:want]
        out.sort(key=lambda r: r[0])
    return out


def widths(mask, y0, y1):
    """Ширина силуэта по каждой строке фигуры (сплошной габарит строки)."""
    w = np.zeros(y1 - y0 + 1)
    for i, y in enumerate(range(y0, y1 + 1)):
        xs = np.nonzero(mask[y])[0]
        w[i] = (xs.max() - xs.min() + 1) if len(xs) else 0
    return w


def landmarks(w):
    """Высотные отметки по излому ширины, в долях роста сверху вниз.

    Плечо — где узкая шея скачком переходит в корпус; подол — где корпус
    скачком переходит в ноги.

    ПОЛОСЫ ПОИСКА ОГРАНИЧЕНЫ НАРОЧНО. Без них «плечо» находилось на 0.002
    роста: голова расширяется от макушки, и самый большой положительный скачок
    ширины приходится на неё, а не на плечи. Плечо ищем ниже головы, подол —
    ниже середины: это не подгонка, а знание того, как устроена фигура.
    """
    n = len(w)
    d = np.diff(w)
    lo, hi = int(n * 0.10), int(n * 0.45)
    top = int(np.argmax(d[lo:hi])) + lo + 1
    lo2, hi2 = int(n * 0.45), int(n * 0.95)
    bot = int(np.argmin(d[lo2:hi2])) + lo2 + 1
    return {"плечо": top / n, "подол": bot / n}


def main(argv=None):
    ap = argparse.ArgumentParser(description="Замер листа-эталона")
    ap.add_argument("sheet")
    ap.add_argument("--figures", type=int, help="сколько фигур ожидать")
    ap.add_argument("--k", action="store_true",
                    help="отношение глубины к ширине (нужен лист анфас+профиль)")
    args = ap.parse_args(argv)

    figs = figures(args.sheet, args.figures)
    if not figs:
        sys.exit("на листе не найдено ни одной фигуры выше трети листа")

    print(f"\n  ЛИСТ: {Path(args.sheet).name} — фигур найдено {len(figs)}\n")
    data = []
    for i, (x0, y0, x1, y1, m) in enumerate(figs, 1):
        w = widths(m, y0, y1)
        h = y1 - y0 + 1
        w45 = w[int(len(w) * ROW_45)]
        lm = landmarks(w)
        data.append((h, w45, w.max()))
        print(f"  фигура {i}: рост {h} px, ширина на 45% высоты {w45:.0f} px, "
              f"макс. ширина {w.max():.0f} px")
        print(f"             плечо на {lm['плечо']:.3f} роста, "
              f"подол на {lm['подол']:.3f}")

    if args.k:
        if len(data) < 2:
            sys.exit("для отношения глубины к ширине нужны анфас И профиль "
                     "одним листом в одном масштабе")
        # приводим к общей высоте: у видов на листе рост обязан совпадать, но
        # округление в пикселях даёт разницу в единицы — нормируем на всякий
        hf, wf, _ = data[0]
        hs, ws, _ = data[1]
        k = (ws / hs) / (wf / hf)
        print(f"\n  ГЛУБИНА / ШИРИНА по листу: {k:.3f}")
        print(f"  У нас в риге (профиль/анфас, замер turnaround): 0.715")
        print(f"  Расхождение: {k - 0.715:+.3f}"
              + ("   <<< профиль нарисован неверно" if abs(k - 0.715) > 0.05 else
                 "   — сходится, болвану можно верить"))
        if abs(hf - hs) / max(hf, hs) > 0.03:
            print(f"\n  ОСТОРОЖНО: рост видов на листе разошёлся "
                  f"({hf} px против {hs} px, {abs(hf-hs)/max(hf,hs):.1%}). "
                  f"Лист нарисован не в одном масштабе, отношение ненадёжно.")
    print()
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
