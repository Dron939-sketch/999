#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
apply_sculpt_proportions.py — ПРОПОРЦИИ СО СКУЛЬПТУРЫ В rig.json.

Части персонажа вынимает `stl_to_rig.py`, но рисунок — это половина дела: части
надо ещё поставить и смерить. Этот шаг переводит замер скульптуры в геометрию
скелета: пивоты под новые viewBox, масштабы под настоящие пропорции, длины
костей под настоящие длины, и включает цилиндр с тростью — в риге они стояли
`blank`, то есть канонический Фримен рендерился без шляпы и без трости.

ГЛАВНАЯ ОСТОРОЖНОСТЬ. В риге 60 поз, и они правят те же поля: 46 поз двигают
голову, 12 масштабируют бёдра, 16 — плащ. Значения в позах АБСОЛЮТНЫЕ. Если
поменять базу и не тронуть позы, поза вернёт старое число и вся правка в ней
пропадёт — молча, только в тех кадрах, где играет эта поза. Поэтому каждой позе
применяется ТА ЖЕ правка, что и базе: смещения сдвигаются на разницу, масштабы
умножаются на отношение. Замысел позы («голова опущена на 21 единицу», «бедро
поджато на 0.8») сохраняется, меняется система отсчёта.

Масштаб кости УМНОЖАЕТСЯ на масштаб предков (см. renderer::collect_bone_
drawables: `entity_scale_x * scale_x`), и у торса он РАЗНЫЙ по осям (1.55 / 1.86).
Поэтому «сделать ногу толщиной 4 единицы» — это не «поставить 4», а поставить с
поправкой на перекос предков, иначе нога выйдет на четверть тоньше замера.

Использование:
    python3 tools/apply_sculpt_proportions.py            # правка + отчёт
    python3 tools/apply_sculpt_proportions.py --dry-run  # только отчёт
"""

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RIG = ROOT / "examples/assets/characters/freeman_rig/rig.json"

# --------------------------------------------------------------------------- #
#  ЗАМЕР СКУЛЬПТУРЫ (единицы STL; переводятся в «пиксели скульптуры» x10)
#
#  Снято по горизонтальным срезам `source/mr_freeman.stl` (см. tools/stl_to_rig.py
#  и freeman_bones.json). Ось Z вверх, значения — уровни в единицах STL.
# --------------------------------------------------------------------------- #
Z_SHOULDER = 29.5      # точка крепления плаща (верх колонны)
Z_HEM = -17.0          # подол
Z_HIP = -6.0           # таз
Z_KNEE = -32.0         # колено
Z_SOLE = -53.0         # подошва
Z_CHIN = 24.6          # низ маски
Z_CROWN = 43.4         # макушка маски
MASK_W = 17.5          # ширина маски
X_MASK = -6.0          # ось маски по X
X_COAT = -4.0          # ось плаща по X
HAT_BRIM_W = 23.0      # ширина полей цилиндра
HAT_CROWN_H = 15.3     # высота тульи над полями
LEG_DX = 6.8           # отстояние стойки от оси плаща
ARM_LEN = 36.4         # плечо+предплечье
SHOULDER_DX = 10.5     # отстояние плечевого сустава от оси плаща
CANE_LEN = 49.5        # древко от кисти до пола

# ШИРИНА БАЛАХОНА — РЕЖИССЁРСКАЯ ПРАВКА ПОВЕРХ ЗАМЕРА, не ошибка замера.
# Скульптура даёт колонну уже, чем она читается на подлинных кадрах: там плащ
# заметно массивнее, и силуэт держится именно им. Множитель стоит ОТДЕЛЬНОЙ
# величиной, а не вплавлен в число масштаба, чтобы было видно, где кончается
# замер и начинается решение художника.
COAT_WIDTH_K = 1.20
JOINT_LAP = 40.0       # заход голени на бедро, чтобы колено не просвечивало

PX = 10.0              # пикселей рига на единицу STL

# Экранная длина плаща сохраняется прежней — иначе все `scales` в готовых
# роликах поедут, и каждый существующий кадр придётся перекадрировать.
OLD_TORSO_SCALE = (1.55, 1.86)
CLOAK_SCREEN_LEN = 392.0 * OLD_TORSO_SCALE[1]                # 729: плащ от плеч вниз

# Новые части: рамка, пивот кости в ней и ПОЛЕ вокруг рисунка (`margin` в
# freeman_bones.json). Делить надо на РИСУНОК, а не на рамку: у плаща поле по 6
# пикселей с каждой стороны, у бедра по 4, и счёт по рамке давал промах в
# несколько процентов на каждой части — они складывались в перекос всей фигуры.
PARTS = {
    "torso": {"box": (335.0, 521.0), "pivot": (162.0, 30.0), "margin": 6.0},
    "thigh_left": {"box": (72.0, 298.0), "pivot": (26.0, 4.0), "margin": 4.0},
    "thigh_right": {"box": (72.0, 298.0), "pivot": (45.0, 4.0), "margin": 4.0},
    "shin_left": {"box": (89.0, 243.0), "pivot": (63.0, 4.0), "margin": 4.0},
    "shin_right": {"box": (89.0, 243.0), "pivot": (25.0, 4.0), "margin": 4.0},
    "cane": {"box": (43.0, 505.0), "pivot": (11.0, 4.0), "margin": 5.0},
}


def coat_axis_shift():
    """На сколько центр НАРИСОВАННОЙ ткани смещён от пивота кости, в px части.

    Пивот плаща — точка анатомии (крепление у плеч), и он ОБЯЗАН стоять на
    одном месте у всех трёх ракурсов, иначе поворот перестанет читаться
    поворотом. Центр самого рисунка с ним не совпадает: скульптура несимметрична
    (фигура сутулится, правое плечо выше), да и правка борта срезает ткань
    только с одной стороны.

    Пока плащ был узким, разница терялась. После расширения на 20% она выросла
    вместе с ним, и маска с ногами оказались заметно левее середины балахона.
    Поэтому маска и стойки центруются не по пивоту, а по РИСУНКУ — число
    читается из самой части, и при любой её перерисовке центровка едет следом.
    """
    txt = (ROOT / "examples/assets/characters/freeman_rig/torso.svg").read_text(
        encoding="utf-8")
    m = re.search(r"Рисунок в этом viewBox: x (\d+)\.\.(\d+)", txt)
    if not m:
        return 0.0
    x0, x1 = float(m.group(1)), float(m.group(2))
    return (x0 + x1) / 2.0 - PARTS["torso"]["pivot"][0]


def ink(name):
    """Рисунок части: ширина и длина НИЖЕ пивота, без поля рамки."""
    p = PARTS[name]
    return (p["box"][0] - 2 * p["margin"],
            p["box"][1] - p["pivot"][1] - p["margin"])
# РИСУНОК, А НЕ РАМКА. Маска обведена с кадра потрейсом, и в своём viewBox
# 160x214 она занимает 136.6x188.8, прижатая к левому верхнему углу; пивот
# [80,190] стоит на 12.7 правее середины яйца. Первый расчёт делил на рамку —
# маска выходила на 21% мельче замера и, главное, ШИРЕ, чем высокая (1:0.85
# вместо 1:1.07), потому что по вертикали запас рамки больше, чем по
# горизонтали. Числа сняты разбором самого пути (см. историю правки).
HEAD_EGG = (136.6, 190.1)       # ширина яйца и высота от пивота до макушки
HEAD_EGG_DX = 12.7              # пивот [80,190] правее середины яйца (67.3):
                                # смещение задаётся до СЕРЕДИНЫ яйца, а ставится
                                # пивот — разницу надо вычесть, иначе маска
                                # уезжает вправо на четверть своей ширины
HEAD_SCALE = (1.05, 0.875)      # масштаб маски в риге — НЕ меняется, см. ниже
HAT_BRIM_PX = 88.0              # ширина полей в рисунке hat.svg (x 6..94)
HAT_CROWN_PX = 54.0             # высота тульи над полями в hat.svg (y 5..59)
HAT_PIVOT_Y = 70.0              # пивот кости внутри рисунка цилиндра
HAT_BOTTOM_PX = 84.0            # низ полей в рисунке
EYE_TOP_LOCAL = 153.0           # верх глаза над подбородком, в px головы
                                # (смещение кости 121 + полувысота 30x1.07)
EYE_CLEARANCE = 15.0            # просвет между полями и глазом, в px головы


def compute():
    """Числа для скелета. Возвращает {кость: {поле: значение}} и отчёт."""
    # Множитель «пиксель скульптуры → пиксель экрана»: длина плаща на экране
    # остаётся прежней, а в скульптуре она (Z_SHOULDER - Z_HEM).
    tsx, tsy = OLD_TORSO_SCALE
    coat_w, coat_len = ink("torso")
    # Множитель «пиксель скульптуры → пиксель экрана» привязан к РИСУНКУ плаща:
    # его экранная длина остаётся прежней (729), а в рисунке она `coat_len`.
    k = CLOAK_SCREEN_LEN / coat_len

    def sculpt_y(z):
        """Экранные пиксели вниз от плеч."""
        return (Z_SHOULDER - z) * PX * k

    out, rep = {}, []
    # Сдвиг в ЭКРАННЫХ пикселях. Считается ГОРИЗОНТАЛЬНЫМ масштабом плаща:
    # рисунок по ширине растянут в (экранная ширина / ширина рамки), и никакого
    # отношения к вертикальному масштабу этот сдвиг не имеет.
    axis_shift = coat_axis_shift() * (coat_w * k * COAT_WIDTH_K
                                      / PARTS["torso"]["box"][0])

    # ── ПЛАЩ ──────────────────────────────────────────────────────────────── #
    # Ширина по скульптуре, высота — прежняя экранная.
    cloak_screen_w = coat_w * k * COAT_WIDTH_K
    out["cloak"] = {
        "pivot": list(PARTS["torso"]["pivot"]),
        "scale": [round(cloak_screen_w / (PARTS["torso"]["box"][0] * tsx), 4),
                  round(CLOAK_SCREEN_LEN / (coat_len * tsy), 4)],
    }
    out["torso"] = {"pivot": list(PARTS["torso"]["pivot"])}
    rep.append(f"плащ на экране: {cloak_screen_w:.0f}x{CLOAK_SCREEN_LEN:.0f} "
               f"(ширина замера {coat_w * k:.0f} x{COAT_WIDTH_K} — режиссёрская "
               f"правка; подол рваный, горб скульптуры срезан: он поза)")

    # ── МАСКА ─────────────────────────────────────────────────────────────── #
    # МАСКА ОСТАЁТСЯ КАК ОБВЕДЕНА. Скульптура даёт яйцо 1:1.07, обводка с кадра —
    # 1:1.34, и соблазн «поправить по скульптуре» был. Не правим, по двум
    # причинам. Первая: обводка снята с ПОДЛИННОГО кадра, скульптура —
    # производная работа, и в споре о самой узнаваемой части персонажа
    # первоисточник главнее. Вторая — цена: глаза, брови и рот висят на маске, и
    # их смещения правят 124 позы. Пробная правка (sx 1.05→1.30) увела глаз с
    # белого ядра на профиле — гейт разворота потерял глаз там, где его должно
    # быть ровно один. Со скульптуры берём то, что она мерит лучше: длины,
    # посадку и размер предметов.
    head = HEAD_SCALE
    # МАСШТАБ маски не трогаем (см. выше), но ПОСАДКУ по горизонтали задаём:
    # яйцо должно стоять по центру нарисованной ткани, иначе после расширения
    # балахона голова читается сдвинутой вбок. Пивот стоит не в середине яйца —
    # его сдвиг внутри рисунка вычитается.
    # МАСКА СТАВИТСЯ РОВНО ПО ЦЕНТРУ ТКАНИ. У скульптуры ось маски на две
    # единицы левее оси плаща (фигура сутулится и голова уведена вбок), и пока
    # балахон был узким, это читалось характерным перекосом. После расширения
    # на 20% тот же сдвиг стал читаться просто съехавшей головой, поэтому
    # боковой член замера здесь отброшен: центровка — решение по кадру, а не
    # по скульптуре. Наклон головы по-прежнему живёт в позах.
    # ВЫСОТА ПОСАДКИ НЕ ТРОГАЕТСЯ (None = «оставить как в риге»). Она, как и
    # сама маска, снята с подлинного кадра и выверена руками; первая версия
    # этого блока вписала сюда подбородок по скульптуре — маска села на 26 px
    # ниже, и гейт разворота завалился по гуляющей макушке.
    mask_dx = axis_shift
    out["head"] = {
        "offset": [round((mask_dx + HEAD_EGG_DX * head[0] * tsx) / tsx, 1),
                   None],
    }
    rep.append(f"маска: масштаб НЕ тронут ({head[0]}, {head[1]}) — обводка с кадра; "
               f"посадка по X — на центр нарисованной ткани")

    # ── ЦИЛИНДР ───────────────────────────────────────────────────────────── #
    # Ребёнок головы: масштаб копится, и он у неё разный по осям.
    accx, accy = tsx * head[0], tsy * head[1]
    mask_h = HEAD_EGG[1] * head[1] * tsy
    out["hat"] = {
        "part": "hat",
        "scale": [round(HAT_BRIM_W * PX * k / (HAT_BRIM_PX * accx), 4),
                  round(HAT_CROWN_H * PX * k / (HAT_CROWN_PX * accy), 4)],
    }
    # ВЫСОТА ПОСАДКИ СЧИТАЕТСЯ ОТ ГЛАЗА, А НЕ ОТ ДОЛИ МАСКИ. Первая версия
    # ставила поля на 0.80 высоты маски — на анфасе глаза оставались видны, и
    # это казалось нормой. Но поля рисуются ПОВЕРХ глаз (z_order 7 против 6), и
    # на сверхкрупном плане с наклоном головы они накрывали глаза целиком:
    # лицо выходило без глаз, с одним ртом. Считаем от верха глаза плюс просвет
    # — тогда поля не могут его задеть ни при каком повороте.
    hat_sy = out["hat"]["scale"][1]
    brim_below = (HAT_BOTTOM_PX - HAT_PIVOT_Y) * hat_sy
    out["hat"]["offset"] = [0, -round(EYE_TOP_LOCAL + EYE_CLEARANCE + brim_below, 1)]
    rep.append(f"цилиндр ВКЛЮЧЁН (было part=blank): поля {HAT_BRIM_W * PX * k:.0f} px, "
               f"тулья {HAT_CROWN_H * PX * k:.0f} px; посадка от верха глаза с "
               f"просветом — иначе поля накрывают глаза на сверхкрупном плане")

    # ── НОГИ ──────────────────────────────────────────────────────────────── #
    thigh_screen = sculpt_y(Z_KNEE) - sculpt_y(Z_HIP)
    shin_screen = sculpt_y(Z_SOLE) - sculpt_y(Z_KNEE)
    t_draw = ink("thigh_left")[1]
    s_draw = ink("shin_left")[1]
    t_sy = thigh_screen / (t_draw * tsy)
    # Поправка на перекос предков: у торса масштаб по x меньше, чем по y, и
    # стойка без поправки выходит на 17% тоньше замера.
    t_sx = t_sy * tsy / tsx
    for side in ("left", "right"):
        out[f"thigh_{side}"] = {
            "pivot": list(PARTS[f"thigh_{side}"]["pivot"]),
            "scale": [round(t_sx, 4), round(t_sy, 4)],
            "offset": [round(((-LEG_DX if side == "left" else LEG_DX) * PX * k
                              + axis_shift) / tsx, 1),
                       round(sculpt_y(Z_HIP) / tsy, 1)],
        }
        out[f"shin_{side}"] = {
            "pivot": list(PARTS[f"shin_{side}"]["pivot"]),
            "scale": [1.0, round(shin_screen / (s_draw * tsy * t_sy), 4)],
            # Голень садится НА бедро с заходом, а не встык. Встык между ними
            # оставалась белая полоса в колене: у бедра снизу поле рамки, у
            # голени сверху отступ до пивота, и два отступа складывались в щель.
            "offset": [0, round(t_draw - JOINT_LAP, 1)],
        }
    rep.append(f"ноги: бедро {thigh_screen:.0f} + голень {shin_screen:.0f} = "
               f"{thigh_screen + shin_screen:.0f} px при плаще {CLOAK_SCREEN_LEN:.0f} "
               f"(было {(112 - 6 + 112 - 8) * 0.9 * tsy:.0f} — фигура стояла на "
               f"обрубках, стоп не было видно)")

    # ── РУКИ ──────────────────────────────────────────────────────────────── #
    # Спиндли не перерисовывались, но были ВДВОЕ короче замера.
    arm_screen = ARM_LEN * PX * k
    ua_draw, fa_draw = 102.0 - 8.0, 145.0 - 12.0
    a_s = arm_screen / ((ua_draw + fa_draw) * tsy)
    for side, sign in (("left", -1), ("right", 1)):
        # ПЛЕЧЕВОЙ СУСТАВ ЕДЕТ ВМЕСТЕ С ПЛАЩОМ. Он задан замером скульптуры, но
        # ширина плаща — режиссёрская (COAT_WIDTH_K), и если оставить сустав на
        # месте, он тонет: при +20% ширины рука стала выходить не из кромки, а
        # на 133 px внутрь силуэта вместо прежних 85, плечевая пружина ушла под
        # ткань, и стык читался как «рука воткнута в плащ». Держим сустав на той
        # же ДОЛЕ полуширины плаща, какую дал замер.
        out[f"upper_arm_{side}"] = {
            "scale": [round(a_s * tsy / tsx, 4), round(a_s, 4)],
            "offset": [round((sign * SHOULDER_DX * PX * k * COAT_WIDTH_K
                              + axis_shift) / tsx, 1), 12],
        }
        out[f"forearm_{side}"] = {"offset": [0, round(ua_draw, 1)]}
    rep.append(f"руки: {arm_screen:.0f} px до кисти "
               f"(было {(ua_draw + fa_draw) * tsy:.0f} — рука не доставала до бедра)")

    # ── ТРОСТЬ ────────────────────────────────────────────────────────────── #
    cane_acc_y = tsy * 0.75                      # кисть уменьшена до 0.75
    cane_draw = ink("cane")[1]
    c_s = CANE_LEN * PX * k / (cane_draw * cane_acc_y)
    out["cane"] = {
        "part": "cane",
        "pivot": list(PARTS["cane"]["pivot"]),
        "scale": [round(c_s, 4), round(c_s, 4)],
        "offset": [0, 8],
    }
    rep.append(f"трость ВКЛЮЧЕНА (было part=blank): {CANE_LEN * PX * k:.0f} px — "
               f"от кисти до пола")

    # ── РОСТ ──────────────────────────────────────────────────────────────── #
    # `height` — делитель кадрирования (renderer: base_scale = ch*0.35/height).
    # Он должен ехать вместе с фигурой, иначе прежние `scales` в роликах дадут
    # другой размер персонажа в кадре.
    # Рост считается ПО СИЛУЭТУ ВМЕСТЕ С ЦИЛИНДРОМ: он часть фигуры, и если
    # мерить без него, общий план будет срезать шляпу.
    hat_top = sculpt_y(Z_CHIN) - (-out["hat"]["offset"][1] * accy) \
        - HAT_CROWN_H * PX * k
    figure = sculpt_y(Z_SOLE) - hat_top
    height = round(470.0 * figure / 806.0)        # 806 — прежний рост в пикселях рига
    rep.append(f"height: {height} (было 470) — фигура выросла до {figure:.0f} px, "
               f"делитель кадрирования едет вместе с ней, чтобы `scales` в готовых "
               f"роликах остались прежними")
    return out, height, rep


# СЕМЬЯ РИСУНКОВ ОДНОЙ КОСТИ. Развороты плаща переложены в ОБЩУЮ рамку с общим
# пивотом и растянуты до новой длины (tools/reframe_part.py) — значит поправка
# масштаба относится к ним так же, как к анфасу: это одна кость с одной
# геометрией. А `arm_out_*` остались профильной рукой в своей рамке, их правка
# не касается: растягивать чужую геометрию вслепую нельзя.
FAMILY = {"cloak": ("torso", "torso_34", "torso_side")}

PROPS_OFF = "bez_predmetov"


def add_props_off_pose(rig):
    """НАКЛАДКА «без предметов» — для замерных стендов.

    Цилиндр и трость теперь надеты по умолчанию, и оба ломают замер. Трость
    свисает НИЖЕ подошв: `karta.py` мерил «ступни» по её наконечнику, персонаж
    вставал на цыпочки в каждом плане, а кадрирование считало рост на 10%
    больше настоящего. Цилиндр ездит вместе с головой: на полуспине голова
    повёрнута, тулья уходит вверх, и гейт разворота объявлял «фигура
    подпрыгивает» — хотя прыгает шляпа, а не фигура.

    Это НАКЛАДКА (`overlays`), а не поза: она кладётся поверх любого ракурса
    разворота и гасит ровно две кости. Иначе пришлось бы держать по замерному
    двойнику на каждый из девяти ракурсов и синхронизировать их вручную.

    В роликах предметы на месте — снимаются только на стенде.
    """
    if PROPS_OFF in rig["poses"]:
        return False
    rig["poses"][PROPS_OFF] = {
        "name": PROPS_OFF,
        "transition_duration": 0.0,
        "bones": {"hat": {"part": "blank"}, "cane": {"part": "blank"}},
    }
    return True


def apply(rig, changes, height):
    """Правка базы + ТА ЖЕ правка каждой позе. Возвращает счётчик правок в позах."""
    bones = {}

    def walk(b):
        bones[b["name"]] = b
        for c in b.get("children", []):
            walk(c)

    walk(rig["skeleton"]["root"])

    deltas = {}
    for name, new in changes.items():
        bone = bones.get(name)
        if bone is None:
            raise SystemExit(f"в риге нет кости {name}")
        d = {}
        if "offset" in new:
            old = bone.get("offset", [0, 0])
            # None в компоненте = «оставить как в риге»: значение снято не со
            # скульптуры, а руками с кадра, и правке не подлежит.
            new["offset"] = [old[i] if new["offset"][i] is None
                             else new["offset"][i] for i in (0, 1)]
            d["offset"] = [new["offset"][0] - old[0], new["offset"][1] - old[1]]
        if "scale" in new:
            old = bone.get("scale", [1.0, 1.0])
            d["scale"] = [new["scale"][0] / old[0], new["scale"][1] / old[1]]
        deltas[name] = d
        bone.update({k: v for k, v in new.items()})

    touched = skipped = 0
    for pose in rig["poses"].values():
        for name, track in pose.get("bones", {}).items():
            d = deltas.get(name)
            if not d:
                continue
            # ПОДМЕНЁННЫЙ РИСУНОК ПРАВКЕ НЕ ПОДЛЕЖИТ. Поправка вычислена под
            # ГЕОМЕТРИЮ НОВОЙ ЧАСТИ; в позах разворота на той же кости висит
            # ДРУГОЙ рисунок (`torso_34`, `torso_side`, `arm_out_upper_r`), и он
            # не менялся. Первый прогон умножил и его: плащ на трёх четвертях
            # съёжился до груди, между подолом и ногами открылось белое поле, а
            # гейт разворота отдал ширину плаща 0.00 — он не нашёл на строке
            # замера ничего шире руки.
            swapped = track.get("part")
            if swapped is not None and swapped not in FAMILY.get(name, ()) \
                    and swapped != bones[name].get("part"):
                skipped += 1
                continue
            if track.get("offset") is not None and "offset" in d:
                track["offset"] = [round(track["offset"][0] + d["offset"][0], 1),
                                   round(track["offset"][1] + d["offset"][1], 1)]
                touched += 1
            if track.get("scale") is not None and "scale" in d:
                track["scale"] = [round(track["scale"][0] * d["scale"][0], 4),
                                  round(track["scale"][1] * d["scale"][1], 4)]
                touched += 1
    rig["height"] = height
    return touched, skipped


def main(argv):
    ap = argparse.ArgumentParser()
    ap.add_argument("--rig", default=str(RIG))
    ap.add_argument("--dry-run", action="store_true")
    a = ap.parse_args(argv)

    changes, height, rep = compute()
    print("ЗАМЕР СКУЛЬПТУРЫ → ГЕОМЕТРИЯ РИГА\n")
    for line in rep:
        print("  •", line)
    print("\nкости:")
    for name, new in changes.items():
        print(f"  {name:18s} " + "  ".join(f"{k}={v}" for k, v in new.items()))

    rig = json.loads(Path(a.rig).read_text(encoding="utf-8"))
    if add_props_off_pose(rig):
        print(f"\nдобавлена накладка `{PROPS_OFF}` — стенд без предметов")
    touched, skipped = apply(rig, changes, height)
    print(f"\nправок в позах: {touched}; пропущено (подменённый рисунок): {skipped}")
    if a.dry_run:
        print("--dry-run: rig.json не тронут")
        return 0
    Path(a.rig).write_text(json.dumps(rig, ensure_ascii=False, indent=2) + "\n",
                           encoding="utf-8")
    print(f"записано: {a.rig}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
