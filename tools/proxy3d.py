#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
proxy3d.py — ОБЪЁМНЫЙ БОЛВАН: ракурс считается, а не рисуется.

ЗАЧЕМ. Сейчас каждый ракурс персонажа — отдельный рисунок, и девять рисунков
не обязаны быть одним телом. Гейт `turnaround.py` это ловит, но починить может
только человек, перерисовав деталь. Сегодняшний замер показывает, где именно
мы врём:

    угол   замер   одно цельное тело   расхождение
      0°   1.000   1.000                +0.000
     22°   0.960   0.965                +0.005
     45°   0.805   0.869                +0.064   <<<
     90°   0.715   0.715                +0.000
    135°   0.790   0.869                +0.079   <<<
    180°   1.000   1.000                +0.000

Одна константа (отношение глубины к ширине) воспроизводит ЧЕТЫРЕ ракурса из
шести с точностью 0.005. Промахивается ровно на тех двух, про которые и так
известно, что они уже листа: три четверти и полуспина нарисованы на 7–8%
у́же, чем дало бы одно тело. Это не придирка к стилю — это доказательство, что
недостающие ракурсы ВЫЧИСЛИМЫ, а нарисованы были на глаз.

КАК. Фримен — почти целиком силуэт: сплошной чёрный балахон, белая маска, руки
и ноги ниточками. Ни светотени, ни материалов. Значит объём нужен ровно для
одного — чтобы знать контур под любым углом. Строим его не мешем, а стопкой
горизонтальных сечений, и берём их из ДВУХ УЖЕ НАРИСОВАННЫХ видов:

    анфас   → полуширина сечения a(y)
    профиль → полуглубина      b(y)

Сечение считаем эллипсом с полуосями a(y), b(y). Тогда проекция при повороте
на θ вокруг вертикали замкнута аналитически:

    полуширина(y, θ) = sqrt( a(y)²·cos²θ + b(y)²·sin²θ )
    центр(y, θ)      = cx(y)·cosθ + cz(y)·sinθ

Второе слагаемое — то самое смещение головы на промежуточных углах, которое у
нас сейчас −0.014 против 0.144 по листу: голова вынесена вперёд по глубине, и
при повороте она обязана уезжать вбок. Нарисовать это на глаз трудно,
посчитать — тривиально.

Ни света, ни материалов, ни текстур — только контур. Поэтому «съёмка с экрана»
здесь не растровый рендер, а сразу вектор: на наезде до 2.01× нечему
рассыпаться, в отличие от пути через PNG и трассировку.

ЧЕГО ЭТОТ ФАЙЛ НЕ ДЕЛАЕТ. Он не трогает риг и не подменяет позы. Это замерочный
шаг: посчитать ракурсы из двух авторских видов и сверить с тем, что в риге
нарисовано. Замена деталей — следующий шаг, и только если числа сойдутся.

ЧТО УЖЕ ВЗЯТО И ЧТО НЕТ. Числа взяты: болван сходится с ригом на 0° (+0.000),
22° (+0.002), 90° (−0.029) и 180° (+0.000), расходясь только на 45° (+0.053) и
135° (+0.068) — на тех самых деталях, что нарисованы у́же одного тела. То есть
недостающие ракурсы ВЫЧИСЛИМЫ по двум авторским видам.

Фигуры пока НЕТ. Отливка здесь одна на весь силуэт, поэтому `--svg` отдаёт
сплошное пятно: голова слита с плащом, ни маски, ни рук, ни ног. Это не
недоделка вывода, а следствие модели — стопка сечений снята с ЦЕЛОГО силуэта,
а не с частей. Следующий шаг — отливка НА КАЖДУЮ ЧАСТЬ со своим смещением по
глубине; оно же даёт вторую половину обещания: смещение головы вбок на
промежуточных углах. Сейчас у нас на 3/4 −0.014 против 0.144 по листу, и чтобы
получить 0.144 при sin45°, голову надо вынести вперёд на 0.204 — это проверяемое
предсказание для следующего шага, а не догадка.

Использование:
    python3 tools/proxy3d.py                    # таблица: болван против рига
    python3 tools/proxy3d.py --svg 45           # силуэт на 45° в SVG
    python3 tools/proxy3d.py --rig <путь>
"""

import argparse
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent))
from karta import ROOT, RIGS, render  # noqa: E402
# ТОТ ЖЕ ПРИБОР, ЧТО У ПРИЁМЩИКА. Первая версия мерила силуэт по-своему —
# габаритом по полосе строк — и разошлась с гейтом на профиле на 0.245. Числа
# несравнимы, если сняты разными приборами: гейт берёт САМЫЙ ДЛИННЫЙ СПЛОШНОЙ
# тёмный отрезок в ОДНОЙ строке на 45% высоты, предварительно залив внутренние
# дыры (маска, негативная рука) и разомкнув тонкие руки-ветки.
from turnaround import _fill_holes, _open_x, widest_run  # noqa: E402

# Тот же ряд, что у приёмщика разворота, — чтобы числа были сравнимы строка в
# строку, а не «примерно про то же».
VIEWS = [(0, "анфас"), (22, "четверть 22°"), (45, "три четверти"),
         (90, "профиль"), (135, "полуспина"), (180, "спина")]

# Позы-источники. Анфас даёт ширину, профиль — глубину. Больше ничего не нужно:
# всё остальное считается. `calm` — эталон анфаса (у `idle` опущена голова, см.
# turnaround.py), `bok_pravo` — профиль.
POSE_FRONT = "calm"
POSE_SIDE = "bok_pravo"

INK = 60          # порог «это тушь», как в karta/turnaround
STAND_Y = 0.62    # якорь фигуры в кадре при замере
STAND_S = 1.0


def rows_halfwidth(gray):
    """Полуширина силуэта по каждой строке — прибором приёмщика разворота.

    Дыры заливаются (маска внутри фигуры, негативная рука в профиль), тонкие
    руки-ветки размыкаются, дальше по каждой строке берётся самый длинный
    сплошной тёмный отрезок. Ровно то, чем гейт снимает ширину плаща, — иначе
    сравнивать болвана с ригом нельзя.
    """
    dark = gray < INK
    ys = np.where(dark.any(1))[0]
    if not len(ys):
        return 0, 0, np.zeros(0)
    y0, y1 = int(ys.min()), int(ys.max())
    body = _open_x(_fill_holes(dark), 12)
    half = np.array([widest_run(body, y, y + 1) / 2.0 for y in range(y0, y1 + 1)])
    return y0, y1, half


def loft(rig_dir):
    """Стопка сечений из двух авторских видов. (a, b) — полуось по X и по Z.

    Оба вида приводятся к общей сетке высоты: рост на всех ракурсах одинаков
    (это первое условие приёмщика разворота и оно выполняется), поэтому строки
    сопоставляются напрямую по доле роста.
    """
    gf = render(rig_dir, POSE_FRONT, STAND_Y, STAND_S)
    gs = render(rig_dir, POSE_SIDE, STAND_Y, STAND_S)
    _, _, a = rows_halfwidth(gf)
    _, _, b = rows_halfwidth(gs)
    n = min(len(a), len(b))
    if n == 0:
        raise SystemExit("не удалось снять силуэт: пустой кадр")
    # приводим профиль к сетке анфаса
    grid = np.linspace(0, 1, n)
    a = np.interp(grid, np.linspace(0, 1, len(a)), a)
    b = np.interp(grid, np.linspace(0, 1, len(b)), b)
    return a, b


def project_halfwidth(a, b, theta_deg):
    """Полуширина проекции эллиптического сечения при повороте на θ."""
    t = np.radians(theta_deg)
    return np.sqrt((a * np.cos(t)) ** 2 + (b * np.sin(t)) ** 2)


# СТРОКА ЗАМЕРА — 45% ВЫСОТЫ ФИГУРЫ, а не максимум по полосе. Это та самая
# строка, по которой снят лист разворотов, и по ней же меряет гейт. Максимум по
# полосе брать нельзя: у разных ракурсов плащ шире в разных местах, и сравнение
# уезжает.
ROW_45 = 0.45


def table(rig_dir):
    a, b = loft(rig_dir)
    i = int(len(a) * ROW_45)
    base = project_halfwidth(a, b, 0)[i]
    return [(ang, name, project_halfwidth(a, b, ang)[i] / base)
            for ang, name in VIEWS]


def to_svg(a, b, theta_deg, width=220, height=392):
    """Силуэт под углом θ — сразу вектор, без растровой стадии."""
    n = len(a)
    hw = project_halfwidth(a, b, theta_deg)
    scale = height / n
    cx = width / 2.0
    k = (width / 2.0 - 4) / max(hw.max(), 1e-6)
    left = [(cx - h * k, i * scale) for i, h in enumerate(hw)]
    right = [(cx + h * k, i * scale) for i, h in enumerate(hw)][::-1]
    pts = left + right
    d = "M" + " L".join(f"{x:.2f} {y:.2f}" for x, y in pts) + " Z"
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {width} {height}" '
            f'width="{width}" height="{height}">\n'
            f'  <path d="{d}" fill="#0e0e0e"/>\n</svg>\n')


def main(argv=None):
    ap = argparse.ArgumentParser(description="Объёмный болван: ракурс считается")
    ap.add_argument("--rig", default=str(ROOT / RIGS / "freeman_rig"))
    ap.add_argument("--svg", type=float, help="выдать силуэт под этим углом")
    args = ap.parse_args(argv)

    if args.svg is not None:
        a, b = loft(args.rig)
        sys.stdout.write(to_svg(a, b, args.svg))
        return 0

    rows = table(args.rig)
    # то, что нарисовано в риге сейчас (замер turnaround.py, пары усреднены)
    drawn = {0: 1.000, 22: 0.960, 45: 0.805, 90: 0.715, 135: 0.790, 180: 1.000}
    print("\n  БОЛВАН ПРОТИВ РИГА — доля ширины плаща\n")
    print("  угол   нарисовано   болван   расхождение")
    worst = 0.0
    for ang, name, val in rows:
        d = val - drawn[ang]
        worst = max(worst, abs(d))
        print(f"  {ang:4}°   {drawn[ang]:9.3f}   {val:6.3f}   {d:+.3f}"
              + ("   <<<" if abs(d) > 0.03 else ""))
    print(f"\n  Максимальное расхождение: {worst:.3f}")
    print("  Расхождение на 45° и 135° ожидаемо: эти две детали нарисованы")
    print("  у́же, чем даёт одно тело. Совпадение на 0°/22°/90°/180° — проверка")
    print("  того, что болван построен по нашей же фигуре, а не по чужой.\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
