#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
razryv.py — ГЕЙТ РАЗРЫВА: несовместимое поставлено рано и оплачено пониманием.

ЗАЧЕМ. Указание студии про механику внимания: человек фиксирует внимание, когда
видит то, чего быть не должно, или слышит то, что не определено контекстом, —
«рыба не в воде». Но фиксация это ЗАЁМ: внимание задержалось, чтобы понять, и
понимание зритель обязан получить. Разрыв без оплаты хуже, чем его отсутствие:
зритель запоминает, что его дёрнули впустую.

ЗАМЕР НА ДЕНЬ ЗАВЕДЕНИЯ. Разрыва нет ни в одном из семи последних роликов. Все
локации правдоподобны — кухня, спортзал, витрина, переговорка, коридор; все хуки
внутри контекста — обвинение, сцена, чужая реплика, число. Цветное пятно приёмом
разрыва не является: красный магнит на дверце холодильника контекстом полностью
объяснён, глаз находит его и отпускает. ЗАМЕТНОСТЬ И НЕСОВМЕСТИМОСТЬ — РАЗНОЕ.

ЧТО ПРОВЕРЯЕТ МАШИНА, А ЧТО ОСТАЁТСЯ НА ЧЕЛОВЕКЕ. Странно ли выглядит предмет,
машина не скажет — это видно и только видно. Но три способа сломать приём она
ловит, и все три встречались в чужих роликах чаще самого приёма:

  1. РАЗРЫВ НЕ ОБЪЯВЛЕН. Пока в шапке нет строки `**РАЗРЫВ:**`, автор не решил,
     что именно несовместимо, — и в ролике этого обычно нет вовсе.
  2. ПОСАДКА ПОЗДНО. Несовместимое должно стоять в ПЕРВОЙ ТРЕТИ: приём работает
     на тех секундах, где решается «листать или смотреть». Разрыв на минуте
     тридцатой — украшение, а не крючок.
  3. НЕ ОПЛАЧЕН. Слово разрыва обязано вернуться во ВТОРОЙ ПОЛОВИНЕ ролика —
     там, где объясняют, зачем оно было. Ровно тем же словом: если объяснение
     говорит о другом, зритель связи не соберёт.

Есть и четвёртый способ — объяснить сразу, в следующей же реплике: заём
возвращается раньше, чем успел сработать. Гейт требует зазора не меньше трети
ролика между посадкой и оплатой.

ФОРМАТ ОБЪЯВЛЕНИЯ. Строка в шапке VO:

    **РАЗРЫВ:** <слово или короткое имя вещи> — <чем оно несовместимо с
    контекстом>. Посажен в VO-N, оплачен в VO-M.

Слово разрыва берётся из первых скобок ⟨⟩ или из первого слова строки, и именно
его гейт ищет в репликах.

Использование:
    python3 tools/razryv.py examples/lektorij/hsp-VO.md
    python3 tools/razryv.py --all
"""

import argparse
import glob
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

RAZRYV = re.compile(r"^\s*\*\*РАЗРЫВ:?\*\*\s*:?\s*(.+?)\s*(?:—|$)", re.M | re.I)
REPL = re.compile(r"^\|\s*VO-?(\d+)\s*\|[^|]*\|[^|]*\|\s*«(.*?)»[^|]*\|([^|]*)\|", re.M)

#  Доли ролика. Посадка — в первой трети (там решается «листать или смотреть»),
#  оплата — во второй половине, и между ними не меньше трети: объяснение,
#  пришедшее следующей репликой, возвращает заём раньше, чем он сработал.
POSADKA = 1 / 3
OPLATA = 1 / 2
ZAZOR = 1 / 3


def osnova(slovo):
    """Грубая основа слова: без последних двух букв, но не короче четырёх.

    Падежи и числа ловятся без словаря: «рыба», «рыбу», «рыбой», «рыбы» дают
    общее начало «рыб». Точное совпадение здесь не годится — автор объявляет
    разрыв в именительном, а в репликах слово живёт во всех падежах.
    """
    s = slovo.lower().strip("«»\"',.;:!? ")
    return s[:-2] if len(s) > 5 else s[:4] if len(s) > 4 else s


def razbor(path):
    t = Path(path).read_text(encoding="utf-8")
    m = RAZRYV.search(t)
    repl = [(int(n), s, loc.strip()) for n, s, loc in REPL.findall(t)]
    return m.group(1).strip() if m else None, repl


KOLCO_POVTOROM = re.compile(r"\*\*КОЛЬЦО:\s*ПОВТОРОМ", re.I)

#  ТРЕТИЙ СПОСОБ ЗАКРЫТЬ КОЛЬЦО: ОБРАЗ МЕНЯЕТ СОСТОЯНИЕ.
#
#  Два прежних способа — возврат самой фразы и повтор ролика в ленте — держат
#  кольцо НА СОВПАДЕНИИ: та же фраза, тот же кадр. Отсюда и две проверки шва:
#  последняя реплика короткая, последний кадр в той же локации, что первый.
#
#  Ролик 27 «Парус» закрывает кольцо иначе. Одна и та же вещь показана в двух
#  состояниях: полотнище лежит свёрнутым на дне лодки с первого её появления и
#  выпрямляется парусом в финале. Место при этом ОБЯЗАНО отличаться — лодка
#  тронулась, — а последняя реплика не сшивка, а расплата по займу. Мерить
#  такое кольцо совпадением места значит требовать, чтобы ничего не менялось,
#  то есть требовать отсутствия того самого приёма.
#
#  Проверяется равносильное и такое же жёсткое: образ стоит в колонке локаций
#  и в первой половине, и во второй — посажен картинкой и картинкой возвращён.
KOLCO_OBRAZOM = re.compile(r"\*\*КОЛЬЦО:\s*ПОВТОРОМ\s+ОБРАЗА", re.I)


def pathlib_read(path):
    return Path(path).read_text(encoding="utf-8")


def proverit(path):
    obyavlen, repl = razbor(path)
    #  ДВА СПОСОБА ЗАКРЫТЬ КОЛЬЦО, И ОНИ ПРОВЕРЯЮТСЯ ПО-РАЗНОМУ.
    #
    #  Первый: якорь возвращает РАССКАЗЧИК — произносит ту же фразу в финале.
    #  Второй: якорь возвращает ПОВТОР РОЛИКА — последний кадр собран
    #  тождественным первому, ролик в ленте идёт по кругу, и первая реплика
    #  звучит второй раз уже с другим весом.
    #
    #  Указание студии: второй способ сильнее. Названное вслух число отбирает у
    #  зрителя ровно ту работу, ради которой стоит пауза, — он и сам его
    #  назовёт, если ему дали чем. Поэтому «якорь звучит в последних трёх
    #  репликах» для зацикленного ролика не требование, а ошибка.
    #
    #  Но оплата обязана быть в любом случае: заём есть заём. В зацикленном
    #  ролике её несёт не повтор фразы, а РАЗБОР — во второй половине зритель
    #  обязан получить всё, из чего число собирается. Это и меряется: корень
    #  слова разрыва должен вернуться во второй половине («дни у кормушки»
    #  оплачивают «девяносто девятый день»), а последняя реплика — остаться
    #  короткой, чтобы шва перед вторым кругом не было.
    povtorom = bool(KOLCO_POVTOROM.search(pathlib_read(path)))
    out = []
    out.append(("разрыв объявлен в шапке", bool(obyavlen),
                "нет строки «**РАЗРЫВ:**» — не сказано, что в ролике "
                "несовместимо с контекстом. Приём внимания, которым мы не "
                "пользовались ни разу (STIL-FRIMENA.md §II.8)"))
    if not obyavlen or not repl:
        return out

    #  Слово разрыва: из ⟨угловых⟩ скобок, если автор их поставил, иначе первое
    #  слово объявления. Скобки нужны там, где имя вещи из двух слов.
    m = re.search(r"⟨(.+?)⟩", obyavlen)
    slovo = m.group(1) if m else obyavlen.split()[0]
    o = osnova(slovo)

    vsego = len(repl)
    gde = [i for i, (_, s, _l) in enumerate(repl) if o in s.lower()]
    out.append((f"слово разрыва «{slovo}» звучит в репликах", bool(gde),
                f"объявлено «{slovo}», но ни в одной реплике его нет. Разрыв, "
                f"который живёт только в шапке, зритель не увидит"))
    if not gde:
        return out

    #  ЧЕМ ОПЛАЧЕН ЗАЁМ — считается по-разному для двух конструкций.
    #
    #  Обычная: оплата это ВОЗВРАТ САМОЙ ФРАЗЫ, её и ищем.
    #
    #  Зацикленная: фразу вернёт второй круг, а во второй половине зритель
    #  обязан получить ВЕЩЬ, которую фраза прячет, — иначе на втором круге ему
    #  нечем будет её прочесть. Вещь эта в шапке объявлена своей строкой:
    #  «**ОБРАЗ:** КОРМУШКА». По ней и меряем: «дни у кормушки» в предпоследней
    #  реплике оплачивают «девяносто девятый день» из первой.
    oplata_gde, chem = gde, f"«{slovo}»"
    if povtorom:
        mo = re.search(r"\*\*ОБРАЗ:\*\*\s*([^.,\n]+)", pathlib_read(path))
        if mo:
            obraz = mo.group(1).strip()
            oo = osnova(obraz.split()[0])
            najdeno = [i for i, (_n, s, _l) in enumerate(repl) if oo in s.lower()]
            if najdeno:
                oplata_gde, chem = najdeno, f"образом «{obraz}»"

    pervoe, poslednee = gde[0] / vsego, oplata_gde[-1] / vsego
    out.append((f"посажен рано (реплика {gde[0] + 1} из {vsego})",
                pervoe <= POSADKA,
                f"разрыв появляется на {pervoe * 100:.0f}% ролика, а работает "
                f"он в первой трети: там решается «листать или смотреть». "
                f"Позже — это украшение, а не крючок"))
    out.append((f"оплачен во второй половине {chem} (реплика {oplata_gde[-1] + 1})",
                poslednee >= OPLATA,
                f"последняя оплата на {poslednee * 100:.0f}% ролика: "
                f"внимание заняли и не вернули понимание. Это хуже, чем не "
                f"ставить разрыв вовсе — зритель запомнит, что его дёрнули"))
    out.append((f"зазор между посадкой и оплатой {(poslednee - pervoe) * 100:.0f}%",
                (poslednee - pervoe) >= ZAZOR,
                "объяснение приходит почти сразу за посадкой: заём возвращается "
                "раньше, чем успел сработать, и внимание не держится"))

    #  ВОЗВРАТ ЯКОРЯ В ФИНАЛ. «Увидел → узнал» это две точки ОДНОГО ролика:
    #  в начале зритель видит мысль и не может её прочесть, в конце узнаёт —
    #  потому что теперь есть чем. Узнавание работает на СОВПАДЕНИИ ПАТТЕРНА,
    #  а не смысла: мозг сверяет ту же фразу, а не пересказ. Перефразировал —
    #  узнавания нет, есть новое утверждение.
    hvost = [i for i in gde if i >= vsego - 3]
    if povtorom:
        out.append(("кольцо закрывает повтор ролика, а не реплика", True,
                    ""))
    else:
        out.append((f"якорь возвращается в последних трёх репликах",
                    bool(hvost),
                    f"последнее упоминание якоря — реплика {gde[-1] + 1} из {vsego}, "
                    f"а узнавание случается на возврате В ФИНАЛ. Верните тот же "
                    f"предмет теми же словами: мозг сверяет паттерн, а не смысл"))

    #  КОЛЬЦО ЗАКРЫВАЕТСЯ ЦЕЛИКОМ: ФРАЗА В ТОЙ ЖЕ ЛОКАЦИИ, ЧТО И КАДР.
    #  Ролик в ленте зациклен, и первый кадр тождествен последнему — это у нас
    #  давно. Но якорь до сих пор мог прозвучать в одном месте, а вернуться в
    #  другом, и тогда кольцо смыкается наполовину: картинка сошлась, а фраза
    #  пришла из чужого кадра. Зритель на втором круге сверяет ОБА канала сразу,
    #  и расхождение читается как склейка, а не как возврат.
    loc_p = repl[gde[0]][2].lower()
    loc_v = repl[hvost[-1]][2].lower() if hvost else ""
    #  «там же» в колонке локации означает предыдущую строку — для сверки это
    #  не имя места, и такую клетку сравнивать бессмысленно.
    if loc_p and loc_v and "там же" not in loc_p and "там же" not in loc_v:
        out.append(("посадка и возврат в одной локации",
                    loc_p.split(",")[0].split(";")[0] == loc_v.split(",")[0].split(";")[0],
                    f"посажен в «{loc_p[:30]}», возвращён в «{loc_v[:30]}». Ролик "
                    f"в ленте зациклен: кадр смыкается, а фраза приходит из "
                    f"другого места — кольцо закрывается наполовину"))

    #  ШВА ПЕРЕД ВТОРЫМ КРУГОМ БЫТЬ НЕ ДОЛЖНО. У зацикленного ролика возврата
    #  фразы нет, поэтому проверяются две другие вещи: последняя реплика
    #  короткая (длинная читается как подпись и объявляет конец там, где конца
    #  не должно быть), и последний кадр стоит в той же локации, что первый —
    #  иначе на склейке круга место меняется рывком.
    if povtorom and KOLCO_OBRAZOM.search(pathlib_read(path)):
        mo = re.search(r"\*\*ОБРАЗ:\*\*\s*([^.,\n]+)", pathlib_read(path))
        oo = osnova(mo.group(1).strip().split()[0]) if mo else ""
        v_kadre = [i for i, (_n, _s, l) in enumerate(repl) if oo and oo in l.lower()]
        rano = bool(v_kadre) and v_kadre[0] < vsego / 2
        pozdno = bool(v_kadre) and v_kadre[-1] >= vsego / 2
        out.append(("образ посажен и возвращён КАРТИНКОЙ", rano and pozdno,
                    f"образ стоит в колонке локаций в {len(v_kadre)} строк(ах). "
                    f"Кольцо через смену состояния держится тем, что вещь ВИДНА "
                    f"в обоих состояниях: свёрнутой в начале и раскрытой в конце"))
    elif povtorom:
        hvostovaya = repl[-1][1]
        out.append((f"последняя реплика короткая ({len(hvostovaya.split())} слов)",
                    len(hvostovaya.split()) <= 8,
                    f"перед вторым кругом стоит реплика в "
                    f"{len(hvostovaya.split())} слов. Длинная читается как "
                    f"подпись и объявляет конец там, где конца по замыслу нет"))
        l_pervoy = repl[0][2].lower().split(",")[0].split(";")[0]
        l_posl = ""
        for _n, _s, l in reversed(repl):
            l = l.lower().strip()
            if l and "там же" not in l:
                l_posl = l.split(",")[0].split(";")[0]
                break
        if l_pervoy and l_posl:
            sovpalo = (l_pervoy == l_posl or "тот же кадр" in l_posl
                       or l_pervoy in l_posl or l_posl in l_pervoy)
            out.append(("круг смыкается в той же локации", sovpalo,
                        f"начинается в «{l_pervoy[:30]}», кончается в "
                        f"«{l_posl[:30]}»: на склейке круга место меняется "
                        f"рывком, и повтор читается как склейка, а не как возврат"))

    #  ПОДТВЕРЖДЕНИЕ КОРОТКОЕ. Рассказчик приходит вторым и подтверждает —
    #  длинное объяснение на возврате отбирает у зрителя находку (§II.9).
    if hvost:
        #  ПОДПИСЬ-КОЛЬЦО ИЗ СЧЁТА ИСКЛЮЧЕНА. «Всё, идём дальше. Лекторий
        #  Мейстера, курс лекций. Поехали!» — восемь слов, фиксированных для
        #  всей серии, и они не объясняют ничего: это сшивка для ленты, чтобы
        #  на втором круге не было видно шва. Считать их как «длинное
        #  объяснение» значит запретить сам возврат якоря в финал — гейт
        #  требовал бы того, чего сам же не пропускает.
        posle = [s for _n, s, _l in repl[hvost[-1] + 1:]
                 if "идём дальше" not in s and "Лекторий Мейстера" not in s]
        slov = sum(len(s.split()) for s in posle)
        out.append((f"после возврата якоря сказано {slov} слов",
                    slov <= 8,
                    f"после возврата якоря идёт ещё {slov} слов. Догадку зритель "
                    f"собирает в паузе, а рассказчик подтверждает коротко: "
                    f"длинное объяснение забирает находку себе (§II.9)"))
    return out


def main(argv):
    ap = argparse.ArgumentParser(description="Гейт разрыва шаблона")
    ap.add_argument("files", nargs="*")
    ap.add_argument("--all", action="store_true", help="карта по всем VO-файлам")
    a = ap.parse_args(argv)

    if a.all:
        print("\n  РАЗРЫВ ПО КАТАЛОГУ\n")
        for p in sorted(glob.glob(str(ROOT / "examples/**/*-VO.md"), recursive=True)):
            ob, _ = razbor(p)
            print(f"    {Path(p).stem.replace('-VO',''):24} {ob or '—'}")
        print()
        return 0

    if not a.files:
        raise SystemExit("укажи VO-файл или --all")
    bad = 0
    for f in a.files:
        print(f"\n  РАЗРЫВ: {Path(f).name}\n")
        for name, ok, why in proverit(f):
            print(f"    [{'OK  ' if ok else 'ПРОВАЛ'}] {name}")
            if not ok:
                bad += 1
                print(f"             → {why}")
    if bad:
        print(f"\n  Приём внимания не работает по {bad} признак(ам).\n")
        return 1
    print("\n  Разрыв посажен и оплачен.\n")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
