#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
obrazec_anketa.py — образец нового видеоряда: 1:28.92–3:22.41.

ЧЕМ ОН ОТЛИЧАЕТСЯ ОТ ПЕРВОЙ СБОРКИ. Там кадр вешался на РАЗДЕЛ и висел
тридцать пять секунд, а разделы к тому же стояли не на своих местах: раскладка
считалась по долям слов СТАТЬИ с сайта, тогда как запись — устная лекция, и
«Откуда берутся настройки» уехало на минуту.

Здесь каждый кадр стоит на СВОЁМ СЛОВЕ из расшифровки. Шесть граф анкеты
появляются по одной ровно тогда, когда их называют; ответы в схеме вписываются
по одному по мере перечисления; пять красных меток стоят на экране ровно те три
секунды, что голос говорит «пять красных», и только потом появляется зелёная.
Двадцать смен вместо двух — и ни одна не назначена, все сняты с записи.

ЦВЕТ. Схему заказала сама запись: «пять красных меток по умолчанию и только
одна зелёная, выбранная». Поэтому в конфиге `monochrome` ВЫКЛЮЧЕН — иначе
движок сотрёт то, что названо голосом. Рисунки и так чёрные по бумаге, так что
вид серии не страдает; контраст вшит в саму графику, а не выкручивается
фильтром.

ПРОЕЗДА ПОЧТИ НЕТ, И ЭТО НАРОЧНО. Правило «кадр не стоит мёртвым» writes про
план, висящий полминуты. Когда картинка меняется каждые две-четыре секунды,
движение даёт САМА СМЕНА, а проезд поверх неё читается дрожанием. Ход остаётся
только на планах длиннее восьми секунд.
"""

import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "examples/lektorij/lekciya-koleya-1-obrazec.anim"
FPS = 24
NACHALO, KONEC = 88.92, 202.41

#  БИТЫ: (время по записи, сет, что звучит). Времена — из
#  examples/lektorij/lekciya-koleya-1-slova.json, не назначены.
BITY = [
    ( 88.92, "lek1a-anketa-0",         "теперь представьте анкету"),
    ( 92.70, "lek1a-anketa-1",         "графа первая — РАБОТА"),
    ( 95.88, "lek1a-anketa-2",         "вторая — ГРАФИК"),
    ( 99.69, "lek1a-anketa-3",         "третья — МЕСТО жительства"),
    (106.65, "lek1a-anketa-4",         "четвёртая — ОТДЫХ"),
    (110.79, "lek1a-anketa-5",         "пятая — ЛЮДИ вокруг"),
    (117.12, "lek1a-anketa-6",         "и шестая — ТЕМП жизни"),
    (121.68, "lek1a-anketa-zapolnena", "у каждого эта анкета заполнена"),
    (130.23, "lek1a-anketa-zapolnena", "сколько граф вы заполняли сами"),
    (142.17, "lek1a-anketa-zapolnena", "было ли решение"),
    (151.38, "lek1a-dve-iz-desyati",   "две-три графы из десятка"),
    (155.61, "lek1a-anketa-zapolnena", "жизнь состоит из настроек"),
    (167.31, "lek1a-telefon",          "как в новом телефоне: рингтон, обои, язык"),
    (174.99, "lek1a-shema-0",          "взгляните на схему"),
    (182.25, "lek1a-shema-1",          "работа — в офисе"),
    (183.93, "lek1a-shema-2",          "график — пять на два"),
    (185.46, "lek1a-shema-3",          "место — город, где родился"),
    (187.41, "lek1a-shema-4",          "отдых — море в августе"),
    (189.06, "lek1a-shema-5",          "люди — семья и два друга"),
    (191.55, "lek1a-shema-6",          "темп — календарь забит"),
    (194.16, "lek1a-shema-metki",      "напротив каждой графы стоит метка"),
    (196.62, "lek1a-shema-krasnye",    "пять красных меток — по умолчанию"),
    (199.71, "lek1a-shema-cvet",       "и только одна зелёная — выбранная"),
]

#  Слово, впечатывающееся поверх кадра. Приём проверен на движке: держать за
#  кадром и телепортировать на месте (`hides` на первом кадре сцены не работает).
SLOVA = {130.23: ("СКОЛЬКО ИЗ НИХ", 0.30), 151.38: ("2 ИЗ 10", 0.22)}

DOLGO = 8.0      # длиннее — добавляем тихий ход камеры
POLE = 0.048     # запас проезда при two-shot и поле рисунка


def sobrat():
    sety = sorted({s for _, s, _ in BITY})
    L = []
    A = L.append
    A("// " + "=" * 74)
    A("//  ОБРАЗЕЦ НОВОГО ВИДЕОРЯДА ЛЕКЦИИ 1: 1:28.92–3:22.41.")
    A("//  Собран tools/obrazec_anketa.py — РУКАМИ НЕ ПРАВИТЬ.")
    A("//")
    A("//  Каждый кадр стоит на СВОЁМ СЛОВЕ из расшифровки записи")
    A("//  (lekciya-koleya-1-slova.json), а не на границе раздела. Двадцать")
    A("//  три смены за 113 секунд против двух в первой сборке.")
    A("//")
    A("//  monochrome ВЫКЛЮЧЕН: запись называет цвет меток («пять красных»,")
    A("//  «одна зелёная»), и фильтр стёр бы то, что сказано голосом.")
    A("// " + "=" * 74)
    for s in sety:
        A(f'import set {s.replace("-", "_")} from "../assets/sets/{s}.svg"')
    A("")
    A("config {")
    for k, v in (("width", 1280), ("height", 720), ("fps", FPS),
                 ("background", "#d4d7cf"), ("monochrome", "false"),
                 ("snow", 0.10), ("on-twos", 2), ("line-boil", 0.55),
                 ("film-grain", 0.04), ("vignette", 0.10),
                 ("film-flicker", 0.02), ("gate-weave", 0.30),
                 ("film-scratch", 0.20), ("film-dust", 0.4)):
        A(f"    {k}: {v}")
    A("}")
    A("")

    granicy = [t for t, _, _ in BITY] + [KONEC]
    for i, (t, setname, chto) in enumerate(BITY):
        kadrov = round((granicy[i + 1] - t) * FPS)
        d = (kadrov - 0.4) / FPS        # чуть ниже кадровой границы: ceil точен
        mm, ss = int(t // 60), t % 60
        A(f'// ── {mm}:{ss:05.2f} ({d:.2f}с) — «{chto}»')
        A(f'scene "b{i:02d}" (duration: 1s, set: {setname.replace("-", "_")}) {{')
        A("    transition static 0.10s")
        A("    camera two-shot")
        ost = d - 0.10
        if t in SLOVA:
            slovo, kogda = SLOVA[t]
            A(f'    let w = text("{slovo}", 84) at (0.5, -2.0)')
            A(f"    wait {kogda:.2f}s")
            A("    w moves-to (0.500, 0.845) over 0.01s")
            ost -= kogda + 0.01
        if d > DOLGO:
            A(f"    camera pan-to (0.500, {0.5 - POLE:.3f}) over 0.01s")
            A(f"    camera pan-to (0.500, {0.5 + POLE:.3f}) "
              f"over {ost - 0.01:.4f}s ease-in-out")
        else:
            A(f"    wait {ost:.4f}s")
        A("}")
        A("")
    return "\n".join(L)


def main():
    OUT.write_text(sobrat() + "\n", encoding="utf-8")
    n = len(BITY)
    dl = KONEC - NACHALO
    print(f"\n  ОБРАЗЕЦ: {dl:.2f}с, планов {n}, "
          f"смена в среднем каждые {dl/n:.1f}с")
    print(f"  (в первой сборке на этом куске было 2 плана по 40с)\n")
    granicy = [t for t, _, _ in BITY] + [KONEC]
    for i, (t, s, chto) in enumerate(BITY):
        print(f"  {int(t//60)}:{t%60:05.2f}  {granicy[i+1]-t:5.2f}с  "
              f"{s[6:]:22s} «{chto}»")
    print(f"\n  записано: {OUT.relative_to(ROOT)}\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
